# Make the package version + release codename available as
# ``{{release}}`` / ``{{version}}`` / ``{{codename}}`` substitutions in
# markdown pages. The codename catalogue (RELEASE_CODENAMES) is
# canonical in ``vibeqc.banner`` so the runtime banner and the docs
# site share one source of truth — when a new release codename is
# assigned, only ``python/vibeqc/banner.py`` needs the edit.
# Load python/vibeqc/banner.py as a standalone module, bypassing
# vibeqc/__init__.py — we only need RELEASE_CODENAMES + the lookup
# helper, and importing the full ``vibeqc`` package requires the
# compiled C++ extension that the CI docs build doesn't have. This
# also keeps banner.py as the single source of truth for the
# codename catalogue (the runtime banner reads the same dict).
def _load_banner_module():
    import importlib.util

    banner_path = _REPO_ROOT / "python" / "vibeqc" / "banner.py"
    if not banner_path.is_file():
        return None
    spec = importlib.util.spec_from_file_location(
        "_vqc_banner_for_docs",
        banner_path,
    )
    if spec is None or spec.loader is None:
        return None
    mod = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(mod)
    except Exception:
        return None
    return mod


