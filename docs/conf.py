def _on_missing_reference(app, env, node, contnode):
    """Suppress unfixable autodoc cross-reference warnings.

    Autodoc generates ``:py:class:`` / ``:py:func:`` roles for every type
    annotation and docstring identifier it encounters.  Many of these
    cannot resolve because:

    * NumPy type aliases (``numpy.float64``, ``numpy.typing.NDArray``)
      are ``TypeAlias`` objects, not classes — they are absent from
      NumPy's intersphinx inventory.
    * ``pybind11_builtins.pybind11_object`` is a pybind11 internal that
      has no documentation inventory.
    * Docstring prose fragments (``Internal``, ``Optional``, ``SPINLOCK``,
      ``READ``, ``ATOMSPIN``, raw dimension numbers like ``3``) are falsely
      parsed as cross-reference targets.
    * Private ``vibeqc._vibeqc_core.*`` types are C++ pybind11 bindings
      whose docstrings the Python-domain resolver cannot navigate.

    Returning the continuation node tells Sphinx to use it as-is
    (plain text, no hyperlink) and **skip the warning**.
    """
    target = node.get("reftarget", "")

    # --- pybind11 internal class ---
    if "pybind11_builtins" in target:
        return contnode

    # --- NumPy type aliases (TypeAlias, not in intersphinx) ---
    if target in ("numpy.float64", "numpy.complex128"):
        return contnode
    if target.startswith("numpy.typing."):
        return contnode

    # --- pybind11-generated C++ bindings under vibeqc._vibeqc_core ---
    if target.startswith("vibeqc._vibeqc_core."):
        return contnode

    # --- Internal / experimental modules (prefix-based) ---
    # These are private Python modules or experimental-dev branches
    # whose types autodoc can't cross-reference.
    if target.startswith("vibeqc.pbc_bipole_common."):
        return contnode
    if target.startswith("vibeqc.periodic.chi."):
        return contnode
    if target.startswith("vibeqc.solvers._"):
        return contnode
    if target.startswith("vibeqc.output.formats.perf."):
        return contnode
    if target.startswith("vibeqc.solvation.cavity."):
        return contnode
    if target.startswith("vibeqc.periodic_k_gdf."):
        return contnode
    if target.startswith("vibeqc.pbc_bipole."):
        return contnode
    if target.startswith("vibeqc.neb."):
        return contnode
    if target.startswith("vibeqc.gcp."):
        return contnode

    # --- vibeqc member references (vibeqc.Module.Class.attr) ---
    # Autosummary generates ``:py:obj:`` roles for every class member.
    # When the C++ extension isn't fully importable during docs builds,
    # these cross-page member references can't resolve.  Suppress them
    # all — they represent real API members that would resolve with a
    # complete build environment.
    if target.startswith("vibeqc.") and target.count(".") >= 2:
        return contnode

    # --- vibeqc module-level references ---
    # ``vibeqc.scf_log``, ``vibeqc.dft_plus_u`` etc. are internal
    # modules that autodoc references but can't cross-reference.
    domain = node.get("refdomain", "")
    reftype = node.get("reftype", "")
    if target.startswith("vibeqc.") and domain == "py" and reftype == "mod":
        return contnode

    # --- Targets containing spaces = docstring prose artefacts ---
    # Real Python identifiers never contain spaces.  These are English
    # sentences that autodoc mistakenly promoted to cross-references.
    if " " in target:
        return contnode

    # --- Bare function names (no module qualifier) ---
    # Autodoc generates unqualified ``:py:func:`` roles for internal
    # helpers mentioned in docstrings.  These never resolve.
    if "." not in target and target not in ("True", "False", "None"):
        domain = node.get("refdomain", "")
        reftype = node.get("reftype", "")
        if domain == "py" and reftype in ("func", "obj"):
            return contnode

    # --- Prose fragments mistakenly parsed as cross-references ---
    # If the target is very long (>60 chars) or contains words that
    # look like English prose, it's not a real identifier.
    if len(target) > 60:
        return contnode

    # --- pybind11_detail (C++ binding internals) ---
    if "pybind11_detail" in target:
        return contnode

    # --- Unqualified short names from docstring prose ---
    # When autodoc encounters a bare class name in a docstring (e.g.
    # "Returns a HubbardSite"), it may generate a ``:py:class:`` role
    # without a module qualifier.  These never resolve and are noise.
    _UNQUALIFIED_PROSE = frozenset(
        {
            "HubbardSite",
            "KPoints",
            "D3BJParams",
            "PerfTracker",
            "BasisSet",
            "Molecule",
            "SolventModel",
            "HessianResult",
            "SpinDet",
            "Crystal",
            "Hamiltonian",
            "StructuredLog",
            "BlochKMesh",
            "BandStructure",
            "PeriodicJKMethod",
            "LevelShiftSchedule",
            "OrbitReducedLatticeMatrix",
            "SmearingResolution",
            "n_ao",
            "n_mo",
            "ndet",
            "n_pts",
            "default True",
            'default ""',
            "default None",
            "optional",
            "True for a range-separated",
            "Human-readable triples selector",
            "Diagnostic",
            "Spin-component-scaled correlation energy",
            "Lebedev algebraic order. Bundled tiers",
            "GAPWExperimentalWarning",
            "D4NativeExperimentalWarning",
            "GCPDataMissing",
            "PeriodicSCFAccelerator",
            "transcorrelated_options / casci_options / caspt2_options",
        }
    )
    if target in _UNQUALIFIED_PROSE:
        return contnode

    # Multi-word prose fragments with a specific prefix.
    if target.startswith(("HubbardSite", "KPoints", "D3BJParams", "PerfTracker")):
        return contnode

    # --- Docstring-prose false positives ---
    # These are English words / internal jargon that autodoc's parser
    # mistakenly promotes to ``:py:class:`` roles.
    _PROSE_ARTIFACTS = frozenset(
        {
            "Internal",
            "Optional",
            "READ",
            "SPINLOCK",
            "ATOMSPIN",
            "Hartree",
            "True",
            "False",
            "None",
            "optional",
            "ndarray",
            "np.ndarray",
            "Path",
            "Molecule",
            "3",
        }
    )
    if target in _PROSE_ARTIFACTS:
        return contnode

    # Multi-word prose fragments that got joined into a single target.
    if target.startswith("SPINLOCK "):
        return contnode
    if target.startswith("open-shell "):
        return contnode
    if target.startswith("READ "):
        return contnode

    # --- Quoted targets (autodoc parsing artefacts) ---
    if target.startswith("'") and target.endswith("'"):
        return contnode

    return None


def _install_duplicate_desc_filter():
    """Add a logging filter that silences known-unfixable Sphinx warnings.

    These come from autosummary artefacts, included root-file
    cross-references, and toctree orphans that are intentional.
    """
    import logging

    sphinx_logger = logging.getLogger("sphinx")

    class _SuppressKnownNoise(logging.Filter):
        def filter(self, record):
            msg = record.getMessage()
            # Duplicate member docs from autosummary (class + module pages).
            if "duplicate object description" in msg:
                return False
            # Autosummary stubs intentionally not in toctrees.
            if "document isn't included in any toctree" in msg:
                return False
            # Root-file cross-refs that resolve relative to repo root
            # (not docs/) when included via MyST {include}.  The stub
            # pages at docs/{CONTRIBUTING,CHANGELOG}.md exist but the
            # included content resolves against the wrong base.
            if "Unknown source document 'CONTRIBUTING'" in msg:
                return False
            if "Unknown source document 'CHANGELOG'" in msg:
                return False
            if "Unknown source document 'CLAUDE'" in msg:
                return False
            if "Unknown source document 'AGENTS'" in msg:
                return False
            # myst.xref_missing for known-broken anchors in deleted docs.
            _KNOWN_MISSING_XREFS = [
                "'docs/license.md'",
            ]
            for xref in _KNOWN_MISSING_XREFS:
                if xref in msg:
                    return False
            return True

    sphinx_logger.addFilter(_SuppressKnownNoise())


def _pinned_qvf_link(source: str, target: str) -> str | None:
    """Adapt known upstream-relative links without altering the pinned pages."""
    source_path = Path(source)
    if source_path.parent != _REPO_ROOT / "docs" / "qvf" / "_vendored":
        return None
    targets = {
        ("GOVERNANCE.md", "conformance/README.md"): "/qvf/conformance",
        ("GOVERNANCE.md", "docs/integration_guide.md"): "/qvf/integration_guide",
        ("integration_guide.md", "../conformance/README.md"): "/qvf/conformance",
        ("library_guide.md", "../cpp/include/qvf/qvf_c.h"): (
            "https://github.com/vibe-qc/qvf/blob/"
            "7660640ce609a1fd3ba03db4dd53df01b798e619/cpp/include/qvf/qvf_c.h"
        ),
    }
    return targets.get((source_path.name, target))


def _resolve_pinned_qvf_links(app, doctree):
    """Keep snapshot links working in both included and standalone pages."""
    from docutils import nodes
    from sphinx import addnodes

    for node in doctree.findall(addnodes.pending_xref):
        target = _pinned_qvf_link(node.source or "", node.get("reftarget", ""))
        if target is None:
            continue
        if target.startswith("https:"):
            node.replace_self(
                nodes.reference("", "", *node.children, refuri=target, internal=False)
            )
        else:
            node["refdomain"] = "std"
            node["reftype"] = "doc"
            node["reftarget"] = target


def setup(app):
    """Register config values + Pygments lexer aliases + warning filter."""
    app.add_config_value("is_dev", is_dev, "env")

    # Adapt only the known upstream paths; every unrelated unresolved link
    # still reaches the standard Sphinx/MyST warning path.
    app.connect("doctree-read", _resolve_pinned_qvf_links)

    # Suppress unfixable autodoc noise — see ``_on_missing_reference``.
    app.connect("missing-reference", _on_missing_reference)

    # Suppress "duplicate object description" warnings.  These come
    # from autosummary generating both a class-level page and a
    # module-level listing that document the same members.
    _install_duplicate_desc_filter()

    # Register fallback Pygments lexer aliases so that fenced code
    # blocks tagged ``jsonc`` / ``ssh-config`` don't produce warnings.
    # We do this inside ``setup()`` because ``_pygments_fallback_lexers``
    # must be defined before the Sphinx builder creates the
    # PygmentsBridge (which happens after ``conf.py`` is imported but
    # before events fire).  ``app.add_lexer`` registers the alias on
    # the existing lexer class without overwriting anything.
    from pygments.lexers import get_lexer_by_name

    for alias, fallback in _pygments_fallback_lexers.items():
        lexer_cls = get_lexer_by_name(fallback).__class__
        app.add_lexer(alias, lexer_cls)
