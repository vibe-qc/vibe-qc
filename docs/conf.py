    # tree (works in the CI container where vibe-qc isn't installed).
    try:
        import tomllib

        with open(_REPO_ROOT / "pyproject.toml", "rb") as f:
            return tomllib.load(f)["project"]["version"]
    except Exception:
        return "0.0.1"


