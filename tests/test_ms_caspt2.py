_MOLS = {"H2": H2, "LiH_R3": LIH, "LiH_R6": LIH_STRETCH}

# σ = 0: same method, same model space, tight gate (matches the existing
# single-state OM gate).  σ ≠ 0: vibe-qc applies the imaginary shift to the
# full nondiagonal H₀ (the basis-independent Forsberg-Malmqvist complex
# shift; same convention on the explicit and direct paths, M5), while
# OpenMolcas adds σ²/Δ to the diagonal of its case-block-diagonal H₀
# representation (sgmdia), a representation-dependent variant.  The two
# agree to <1e-8 without intruders (H2O/cc-pVDZ, M5) but diverge near the
# intruders the shift exists for (stretched LiH root 2): observed 1.3e-5
# (ms) / 1.7e-4 (xms) here.  That is convention-level arbitrariness of the
# regularizer, not an implementation error; gate accordingly.
_OM_TOL = 5e-6
_OM_TOL_SHIFTED = 5e-4


class TestMSCASPT2OpenMolcasParity:
    @pytest.mark.parametrize("key", list(_OM_MS))
    def test_ms_xms_vs_openmolcas(self, key):
        system, basis, n_core, n_act, n_elec, mode, imag = key
        ras_ref, ms_ref = _OM_MS[key]
        nroots = len(ms_ref)
        res = _ms(
            _MOLS[system],
            basis,
            n_core,
            n_act,
            n_elec,
            nroots=nroots,
            mode=mode,
            imaginary=imag,
        )
        tol = _OM_TOL if imag == 0.0 else _OM_TOL_SHIFTED
        # model-space reference roots (spin-filtered CASCI on HF orbitals
        # vs OpenMolcas CSF-based RASSCF CIonly roots); for XMS undo the
        # model-space rotation first (ref_energies are the rotated states'
        # diagonal ⟨ĩ|H|ĩ⟩, not the CASCI eigenvalues).
        u = res.xms_rotation
        casci_roots = np.diag(u @ np.asarray(res.ref_hamiltonian) @ u.T)
        assert np.abs(casci_roots - ras_ref).max() < _OM_TOL
        # the multi-state eigenvalues
        assert np.abs(np.asarray(res.energies) - ms_ref).max() < tol
        if key in _OM_MS_SS:
            assert np.abs(np.asarray(res.ss_energies) - _OM_MS_SS[key]).max() < tol

    def test_ms_differs_from_ss_where_coupled(self):
        # At the stretched-LiH avoided crossing the MS rotation is real
        # physics: the recorded OM MS roots differ from the OM SS roots by
        # ~0.6 mHa, and XMS differs from MS by ~25 mHa (strong mixing).
        key_ms = ("LiH_R6", "sto-3g", 1, 2, 2, "ms", 0.0)
        key_xms = ("LiH_R6", "sto-3g", 1, 2, 2, "xms", 0.0)
        _, ms_roots = _OM_MS[key_ms]
        _, xms_roots = _OM_MS[key_xms]
        ss_roots = _OM_MS_SS[key_ms]
        assert abs(ms_roots[0] - ss_roots[0]) > 1e-4
        assert abs(xms_roots[0] - ms_roots[0]) > 1e-3


# OpenMolcas full &RASSCF (ci_only=False), CIRoot = 2 2 1, LiH/STO-3G R=3.0
# CAS(2,2): the SA2 reference the spin-pure SA-CASSCF must reproduce
# (recorded 2026-06-10 from the same runner runs as the composition
# constants in tests/test_runner_ms_caspt2.py).
_OM_SA2_CASSCF_LIH = [-7.85516481, -7.72558848]


class TestSpinPureSACASSCF:
    """⟨S²⟩-filtered state-averaged CASSCF root selection (M10)."""

    def test_spin_pure_sa_casscf_matches_openmolcas(self):
        # With the filter, vibe-qc averages the two lowest singlets and
        # must land in OpenMolcas's singlet-averaged RASSCF solution
        # (LiH is a safe unique-minimum parity system).
        H = _ham(LIH, "sto-3g")
        sc = casscf(
            H.h1e,
            H.h2e,
            n_active_elec=2,
            n_active_orb=2,
            n_core=1,
            nuclear_repulsion=H.nuclear_repulsion,
            ms2=0,
            nroots=2,
            spin_pure=True,
        )
        assert sc.converged
        s2 = [
            _s2_expectation(sc.cas.ci_coeffs_all[:, k], sc.cas.determinants, 2, 0)
            for k in range(2)
        ]
        assert max(abs(s) for s in s2) < 1e-8
        assert np.abs(np.asarray(sc.e_totals) - _OM_SA2_CASSCF_LIH).max() < 5e-6

    def test_default_sa_casscf_is_spin_pure(self):
        # Since 2026-06-11, spin_pure=None resolves to True for SA runs
        # (nroots > 1): the default average is the two lowest singlets,
        # landing in OpenMolcas's singlet-averaged RASSCF solution.
        H = _ham(LIH, "sto-3g")
        sc = casscf(
            H.h1e,
            H.h2e,
            n_active_elec=2,
            n_active_orb=2,
            n_core=1,
            nuclear_repulsion=H.nuclear_repulsion,
            ms2=0,
            nroots=2,
        )
        assert sc.converged
        s2 = [
            _s2_expectation(sc.cas.ci_coeffs_all[:, k], sc.cas.determinants, 2, 0)
            for k in range(2)
        ]
        assert max(abs(s) for s in s2) < 1e-8
        assert np.abs(np.asarray(sc.e_totals) - _OM_SA2_CASSCF_LIH).max() < 5e-6

    def test_spin_pure_false_keeps_ms_sector_roots(self):
        # The deliberate mixed-spin ensemble opt-out (the pre-2026-06-11
        # default): the raw M_s=0 average includes the triplet as root 1.
        H = _ham(LIH, "sto-3g")
        sc = casscf(
            H.h1e,
            H.h2e,
            n_active_elec=2,
            n_active_orb=2,
            n_core=1,
            nuclear_repulsion=H.nuclear_repulsion,
            ms2=0,
            nroots=2,
            spin_pure=False,
        )
        assert sc.converged
        s2_root1 = _s2_expectation(
            sc.cas.ci_coeffs_all[:, 1], sc.cas.determinants, 2, 0
        )
        assert abs(s2_root1 - 2.0) < 1e-6
