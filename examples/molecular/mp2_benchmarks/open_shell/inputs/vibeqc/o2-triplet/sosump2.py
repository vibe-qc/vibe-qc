"""o2-triplet (UHF + sosump2).

Generated by: examples/molecular/mp2_benchmarks/open_shell/generate_inputs.py

Method:   SOS-RI-UMP2 (Jung 2004: c_os=1.3, c_ss=0)
Basis:    cc-pvtz
Aux:      cc-pvtz-ri
Core:     all-electron (explicit historical benchmark convention)
Converger:    plain DIIS (matched to ORCA NoSOSCF NoTRAH SCFCONV8)
"""

from pathlib import Path
import vibeqc as vq

HERE = Path(__file__).resolve().parent
STEM = Path(__file__).stem

mol = vq.Molecule(
    [
    vq.Atom( 8, [    0.00000000,     0.00000000,     0.00000000]),  # O
    vq.Atom( 8, [    0.00000000,     0.00000000,     2.28184413]),  # O
    ],
    charge=0,
    multiplicity=3,
)

basis = vq.BasisSet(mol, "cc-pvtz")

uhf_opts = vq.UHFOptions()
uhf_opts.conv_tol_energy = 1.0e-08
uhf_opts.conv_tol_grad = 1.0e-06
uhf_opts.max_iter = 200
uhf_opts.scf_accelerator = vq.SCFAccelerator.DIIS
uhf_opts.diis_subspace_size = 8
uhf_opts.damping = 0.0
uhf_opts.linear_dep_threshold = 1.0e-07
hf = vq.run_uhf(mol, basis, uhf_opts)
assert hf.converged, f"UHF did not converge: {hf}"

mp2 = vq.run_sos_ump2(mol, basis, hf,
                      density_fit=True,
                      aux_basis="cc-pvtz-ri",
                      frozen_core=False)

result = {
    "system": "o2-triplet", "variant": "sosump2",
    "e_hf": hf.energy, "e_correlation": mp2.e_correlation,
    "e_total": mp2.e_total,
    "e_aa": mp2.e_aa, "e_bb": mp2.e_bb, "e_ab": mp2.e_ab,
    "n_frozen_core": mp2.n_frozen_core,
    "s_squared_uhf": hf.s_squared,
    "n_scf_iter": hf.n_iter, "scf_converged": hf.converged,
}

out_path = (HERE / STEM).with_suffix(".result")
out_path.write_text(repr(result) + "\n")
print(repr(result))
