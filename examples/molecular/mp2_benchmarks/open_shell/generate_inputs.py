"""Emit vibe-qc + ORCA inputs for the open-shell UMP2 complement.

Mirrors ``../s22/generate_inputs.py`` but for the UMP2 variants on the
small open-shell systems in ``geometries/``. Re-uses the converger
profile from the S22 directory so the "same converger in ORCA and
vibe-qc" guarantee carries through.

Per system × per variant we emit one input on each side. There is no
counterpoise / monomer book-keeping here — these systems are isolated
radicals, not dimers (with the partial exception of OH-H2O, where the
benchmark question is the absolute UMP2 energy rather than a binding
energy).

Every UMP2-bearing route is explicitly all-electron on both sides so this
historical parity protocol does not inherit either program's current default.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "s22"))

from converger import (  # noqa: E402  — explicit sys.path edit above
    ORCA_SCF_BLOCK,
    ORCA_SIMPLE_TOLS,
    vibeqc_options_snippet,
)

ORBITAL_BASIS = "cc-pvtz"
ORBITAL_BASIS_ORCA = "cc-pVTZ"
RI_AUX_VQ = "cc-pvtz-ri"
RI_AUX_ORCA = "cc-pVTZ/C"

# Each entry: (tag, multiplicity, comment-for-input-file)
SYSTEMS: list[tuple[str, int]] = [
    ("oh-radical", 2),
    ("o2-triplet", 3),
    ("ch3-radical", 2),
    ("oh-h2o", 2),
]

VARIANTS = ("ump2", "riump2", "scsump2", "sosump2")

GEOM_DIR = HERE / "geometries"
INPUTS_DIR = HERE / "inputs"

SYM_TO_Z = {
    "H": 1, "He": 2, "Li": 3, "Be": 4, "B": 5, "C": 6, "N": 7, "O": 8,
    "F": 9, "Ne": 10, "Na": 11, "Mg": 12, "Al": 13, "Si": 14, "P": 15,
    "S": 16, "Cl": 17, "Ar": 18,
}


def read_xyz(path: Path) -> list[tuple[str, float, float, float]]:
    lines = path.read_text().splitlines()
    n = int(lines[0])
    atoms = []
    for ln in lines[2 : 2 + n]:
        sym, x, y, z = ln.split()
        atoms.append((sym, float(x), float(y), float(z)))
    return atoms


def _vibeqc_atoms_block(atoms, indent: str = "    ") -> str:
    rows = []
    for sym, x, y, z in atoms:
        bx, by, bz = x * 1.8897259886, y * 1.8897259886, z * 1.8897259886
        rows.append(f"{indent}vq.Atom({SYM_TO_Z[sym]:>2d}, [{bx:>14.8f}, {by:>14.8f}, {bz:>14.8f}]),  # {sym}")
    return "\n".join(rows)


VIBEQC_HEADER = '''"""{tag} (UHF + {variant}).

Generated by: examples/molecular/mp2_benchmarks/open_shell/generate_inputs.py

Method:   {method}
Basis:    {orbital_basis}
{aux_line}Core:     all-electron (explicit historical benchmark convention)
Converger:    plain DIIS (matched to ORCA NoSOSCF NoTRAH SCFCONV8)
"""

from pathlib import Path
import vibeqc as vq

HERE = Path(__file__).resolve().parent
STEM = Path(__file__).stem

mol = vq.Molecule(
    [
{atoms}
    ],
    charge=0,
    multiplicity={mult},
)

basis = vq.BasisSet(mol, "{orbital_basis}")
'''


def write_vibeqc_input(tag: str, mult: int, variant: str, out_dir: Path) -> Path:
    atoms = read_xyz(GEOM_DIR / f"{tag}.xyz")
    atoms_block = _vibeqc_atoms_block(atoms)
    uhf_opts_snippet = vibeqc_options_snippet("uhf_opts").rstrip()

    if variant == "ump2":
        method = "canonical UMP2"
        aux_line = ""
        body = f'''
uhf_opts = vq.UHFOptions()
{uhf_opts_snippet}
hf = vq.run_uhf(mol, basis, uhf_opts)
assert hf.converged, f"UHF did not converge: {{hf}}"

ump2_opts = vq.UMP2Options()
ump2_opts.n_frozen_core = 0
ump2_opts.density_fit = False
mp2 = vq.run_ump2(mol, basis, hf, ump2_opts)

result = {{
    "system": "{tag}", "variant": "ump2",
    "e_hf": hf.energy, "e_correlation": mp2.e_correlation,
    "e_total": mp2.e_total,
    "e_aa": mp2.e_aa, "e_bb": mp2.e_bb, "e_ab": mp2.e_ab,
    "n_frozen_core": mp2.n_frozen_core,
    "s_squared_uhf": hf.s_squared,
    "n_scf_iter": hf.n_iter, "scf_converged": hf.converged,
}}
'''
    elif variant == "riump2":
        method = "RI-UMP2"
        aux_line = f"Aux:      {RI_AUX_VQ}\n"
        body = f'''
uhf_opts = vq.UHFOptions()
{uhf_opts_snippet}
hf = vq.run_uhf(mol, basis, uhf_opts)
assert hf.converged, f"UHF did not converge: {{hf}}"

ump2_opts = vq.UMP2Options()
ump2_opts.n_frozen_core = 0
ump2_opts.density_fit = True
ump2_opts.aux_basis = "{RI_AUX_VQ}"
mp2 = vq.run_ump2(mol, basis, hf, ump2_opts)

result = {{
    "system": "{tag}", "variant": "riump2",
    "e_hf": hf.energy, "e_correlation": mp2.e_correlation,
    "e_total": mp2.e_total,
    "e_aa": mp2.e_aa, "e_bb": mp2.e_bb, "e_ab": mp2.e_ab,
    "n_frozen_core": mp2.n_frozen_core,
    "s_squared_uhf": hf.s_squared,
    "n_scf_iter": hf.n_iter, "scf_converged": hf.converged,
}}
'''
    elif variant == "scsump2":
        method = "SCS-RI-UMP2 (Grimme 2003: c_os=6/5, c_ss=1/3)"
        aux_line = f"Aux:      {RI_AUX_VQ}\n"
        body = f'''
uhf_opts = vq.UHFOptions()
{uhf_opts_snippet}
hf = vq.run_uhf(mol, basis, uhf_opts)
assert hf.converged, f"UHF did not converge: {{hf}}"

mp2 = vq.run_scs_ump2(mol, basis, hf,
                      density_fit=True,
                      aux_basis="{RI_AUX_VQ}",
                      frozen_core=False)

result = {{
    "system": "{tag}", "variant": "scsump2",
    "e_hf": hf.energy, "e_correlation": mp2.e_correlation,
    "e_total": mp2.e_total,
    "e_aa": mp2.e_aa, "e_bb": mp2.e_bb, "e_ab": mp2.e_ab,
    "n_frozen_core": mp2.n_frozen_core,
    "s_squared_uhf": hf.s_squared,
    "n_scf_iter": hf.n_iter, "scf_converged": hf.converged,
}}
'''
    elif variant == "sosump2":
        method = "SOS-RI-UMP2 (Jung 2004: c_os=1.3, c_ss=0)"
        aux_line = f"Aux:      {RI_AUX_VQ}\n"
        body = f'''
uhf_opts = vq.UHFOptions()
{uhf_opts_snippet}
hf = vq.run_uhf(mol, basis, uhf_opts)
assert hf.converged, f"UHF did not converge: {{hf}}"

mp2 = vq.run_sos_ump2(mol, basis, hf,
                      density_fit=True,
                      aux_basis="{RI_AUX_VQ}",
                      frozen_core=False)

result = {{
    "system": "{tag}", "variant": "sosump2",
    "e_hf": hf.energy, "e_correlation": mp2.e_correlation,
    "e_total": mp2.e_total,
    "e_aa": mp2.e_aa, "e_bb": mp2.e_bb, "e_ab": mp2.e_ab,
    "n_frozen_core": mp2.n_frozen_core,
    "s_squared_uhf": hf.s_squared,
    "n_scf_iter": hf.n_iter, "scf_converged": hf.converged,
}}
'''
    else:
        raise ValueError(f"unknown variant {variant!r}")

    body += '''
out_path = (HERE / STEM).with_suffix(".result")
out_path.write_text(repr(result) + "\\n")
print(repr(result))
'''

    text = (
        VIBEQC_HEADER.format(
            tag=tag, mult=mult, variant=variant,
            method=method, orbital_basis=ORBITAL_BASIS,
            aux_line=aux_line, atoms=atoms_block,
        )
        + body
    )

    out_dir.mkdir(parents=True, exist_ok=True)
    p = out_dir / f"{variant}.py"
    p.write_text(text)
    return p


def _orca_simple_input(variant: str) -> str:
    base = f"{ORBITAL_BASIS_ORCA} {ORCA_SIMPLE_TOLS}"
    if variant == "ump2":
        return f"! MP2 {base}"
    if variant == "riump2":
        return f"! RI-MP2 {RI_AUX_ORCA} {base}"
    if variant == "scsump2":
        return f"! SCS-MP2 {RI_AUX_ORCA} {base}"
    if variant == "sosump2":
        return f"! SOS-MP2 {RI_AUX_ORCA} {base}"
    raise ValueError(variant)


def write_orca_input(tag: str, mult: int, variant: str, out_dir: Path,
                     nprocs: int = 1) -> Path:
    atoms = read_xyz(GEOM_DIR / f"{tag}.xyz")
    lines = [
        _orca_simple_input(variant),
        ORCA_SCF_BLOCK.rstrip(),
    ]
    if nprocs > 1:
        lines.append(f"%pal nprocs {nprocs} end")
    lines.append(f"*xyz 0 {mult}")
    for sym, x, y, z in atoms:
        lines.append(f"  {sym:<2s} {x:>15.8f} {y:>15.8f} {z:>15.8f}")
    lines.append("*")
    lines.append("")
    out_dir.mkdir(parents=True, exist_ok=True)
    p = out_dir / f"{variant}.inp"
    p.write_text("\n".join(lines))
    return p


def generate_all(nprocs_orca: int = 1) -> tuple[int, int]:
    n_vq = n_orca = 0
    for tag, mult in SYSTEMS:
        for variant in VARIANTS:
            write_vibeqc_input(tag, mult, variant, INPUTS_DIR / "vibeqc" / tag)
            write_orca_input(tag, mult, variant, INPUTS_DIR / "orca" / tag,
                             nprocs=nprocs_orca)
            n_vq += 1
            n_orca += 1
    return n_vq, n_orca


if __name__ == "__main__":
    n_vq, n_orca = generate_all()
    print(f"  vibe-qc inputs: {n_vq}")
    print(f"  ORCA inputs:    {n_orca}")
