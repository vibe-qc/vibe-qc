    vq.Atom( 6, [    1.19851506,     1.42606244,     2.28103816]),  # C
    vq.Atom( 6, [    2.49641005,     1.65116055,     0.00000000]),  # C
    vq.Atom( 6, [    1.19851506,     1.42606244,    -2.28103816]),  # C
    vq.Atom( 1, [   -2.40363603,     0.79487847,    -4.05022968]),  # H
    vq.Atom( 1, [   -4.70583440,     0.38784377,     0.00000000]),  # H
    vq.Atom( 1, [   -2.40363603,     0.79487847,     4.05022968]),  # H
