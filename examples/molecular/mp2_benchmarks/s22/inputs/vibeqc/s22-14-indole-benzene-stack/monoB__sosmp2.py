from pathlib import Path
import vibeqc as vq

HERE = Path(__file__).resolve().parent
STEM = Path(__file__).stem

mol = vq.Molecule(
    [
    vq.Atom( 1, [   -5.55912921,     1.69202928,     4.20257183]),  # H
    vq.Atom( 6, [   -3.82115332,     0.80474737,     3.59303977]),  # C
    vq.Atom( 6, [   -1.54001670,     2.02965132,     3.98108234]),  # C
    vq.Atom( 1, [   -1.48372384,     3.86332028,     4.88609177]),  # H
    vq.Atom( 6, [    0.70000855,     0.84902592,     3.18370792]),  # C
    vq.Atom( 6, [    3.30864923,     1.51913844,     3.24919562]),  # C
    vq.Atom( 1, [    4.13285115,     3.21220934,     4.02056268]),  # H
    vq.Atom( 6, [    4.62063686,    -0.43666692,     2.14546506]),  # C
    vq.Atom( 7, [    2.95675259,    -2.29371388,     1.42776055]),  # N
    vq.Atom( 6, [    0.54069105,    -1.56270626,     2.00665316]),  # C
    vq.Atom( 6, [   -1.75454765,    -2.80683288,     1.62647525]),  # C
    vq.Atom( 1, [   -1.83855221,    -4.64019325,     0.72452340]),  # H
    vq.Atom( 6, [   -3.92927852,    -1.59070860,     2.43329490]),  # C
    vq.Atom( 1, [   -5.74287237,    -2.49516509,     2.16721335]),  # H
    vq.Atom( 1, [    3.41581975,    -3.84879793,     0.44088025]),  # H
    vq.Atom( 1, [    6.61948224,    -0.65863451,     1.83213338]),  # H
    ],
    charge=0,
    multiplicity=1,
)

basis = vq.BasisSet(mol, "cc-pvtz")

rhf_opts = vq.RHFOptions()
rhf_opts.conv_tol_energy = 1.0e-08
rhf_opts.conv_tol_grad = 1.0e-06
rhf_opts.max_iter = 200
rhf_opts.scf_accelerator = vq.SCFAccelerator.DIIS
rhf_opts.diis_subspace_size = 8
rhf_opts.damping = 0.0
rhf_opts.linear_dep_threshold = 1.0e-07
hf = vq.run_rhf(mol, basis, rhf_opts)
assert hf.converged, f"RHF did not converge: {hf}"

mp2 = vq.run_sos_mp2(mol, basis, hf,
                     density_fit=True,
                     aux_basis="cc-pvtz-ri",
                     frozen_core=False)

result = {
    "system": "s22-14-indole-benzene-stack",
    "body": "monoB",
    "variant": "sosmp2",
    "e_hf": hf.energy,
    "e_correlation": mp2.e_correlation,
    "e_total": mp2.e_total,
    "e_os": mp2.e_os,
    "e_ss": mp2.e_ss,
    "n_frozen_core": mp2.n_frozen_core,
    "n_scf_iter": hf.n_iter,
    "scf_converged": hf.converged,
}

out_path = (HERE / STEM).with_suffix(".result")
out_path.write_text(repr(result) + "\n")
print(repr(result))
