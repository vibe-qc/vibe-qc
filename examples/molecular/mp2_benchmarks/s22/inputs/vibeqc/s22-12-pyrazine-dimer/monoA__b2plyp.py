"""S22-12 pyrazine-dimer — body=monoA, variant=b2plyp.

Reference: Jurečka, Šponer, Černý, Hobza, PCCP 8, 1985 (2006).
Generated by: examples/molecular/mp2_benchmarks/s22/generate_inputs.py

Method:   B2PLYP (Grimme 2006 double hybrid)
Basis:    cc-pvtz
Aux:      def2-universal-jkfit (RKS DF) + cc-pvtz-ri (MP2 correction)
Core:     all-electron (explicit historical benchmark convention)
Converger:    plain DIIS (matched to ORCA NoSOSCF NoTRAH SCFCONV8)
"""

from pathlib import Path
import vibeqc as vq

HERE = Path(__file__).resolve().parent
STEM = Path(__file__).stem

mol = vq.Molecule(
    [
    vq.Atom( 6, [   -2.35684622,    -2.21442098,    -1.31551158]),  # C
    vq.Atom( 6, [   -2.35684622,    -2.21442098,     1.31551158]),  # C
    vq.Atom( 7, [   -0.48934643,    -3.25708844,     2.67297886]),  # N
    vq.Atom( 6, [    1.38239635,    -4.28064907,     1.31662652]),  # C
    vq.Atom( 6, [    1.38239635,    -4.28064907,    -1.31662652]),  # C
    vq.Atom( 7, [   -0.48934643,    -3.25708844,    -2.67297886]),  # N
    vq.Atom( 1, [   -3.89932920,    -1.36498669,    -2.35701686]),  # H
    vq.Atom( 1, [   -3.89932920,    -1.36498669,     2.35701686]),  # H
    vq.Atom( 1, [    2.92680837,    -5.12650195,     2.35754731]),  # H
    vq.Atom( 1, [    2.92680837,    -5.12650195,    -2.35754731]),  # H
    ],
    charge=0,
    multiplicity=1,
)

basis = vq.BasisSet(mol, "cc-pvtz")

rks_opts = vq.RKSOptions()
rks_opts.conv_tol_energy = 1.0e-08
rks_opts.conv_tol_grad = 1.0e-06
rks_opts.max_iter = 200
rks_opts.scf_accelerator = vq.SCFAccelerator.DIIS
rks_opts.diis_subspace_size = 8
rks_opts.damping = 0.0
rks_opts.linear_dep_threshold = 1.0e-07
db = vq.run_b2plyp(mol, basis,
                   density_fit=True,
                   aux_basis="def2-universal-jkfit",
                   density_fit_mp2=True,
                   aux_basis_mp2="cc-pvtz-ri",
                   rks_options=rks_opts)

result = {
    "system": "s22-12-pyrazine-dimer",
    "body": "monoA",
    "variant": "b2plyp",
    "e_hf": db.rks.energy,             # RKS-hybrid energy (NOT pure HF)
    "e_correlation": db.mp2.e_correlation,
    "e_total": db.e_total,
    "e_os": db.mp2.e_os,
    "e_ss": db.mp2.e_ss,
    "n_frozen_core": db.mp2.n_frozen_core,
    "n_scf_iter": db.rks.n_iter,
    "scf_converged": db.rks.converged,
}

out_path = (HERE / STEM).with_suffix(".result")
out_path.write_text(repr(result) + "\n")
print(repr(result))
