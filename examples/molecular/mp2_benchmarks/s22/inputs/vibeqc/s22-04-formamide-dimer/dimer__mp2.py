"""S22-04 formamide-dimer — body=dimer, variant=mp2.

Reference: Jurečka, Šponer, Černý, Hobza, PCCP 8, 1985 (2006).
Generated by: examples/molecular/mp2_benchmarks/s22/generate_inputs.py

Method:   canonical RMP2
Basis:    cc-pvtz
Core:     all-electron (explicit historical benchmark convention)
Converger:    plain DIIS (matched to ORCA NoSOSCF NoTRAH SCFCONV8)
"""

from pathlib import Path
import vibeqc as vq

HERE = Path(__file__).resolve().parent
STEM = Path(__file__).stem

mol = vq.Molecule(
    [
    vq.Atom( 6, [   -3.81469348,     0.09993438,     0.00000000]),  # C
    vq.Atom( 8, [   -2.74426008,     2.16115489,     0.00000000]),  # O
    vq.Atom( 7, [   -2.66029955,    -2.15898171,     0.00000000]),  # N
    vq.Atom( 1, [   -3.71254812,    -3.73605631,     0.00000000]),  # H
    vq.Atom( 1, [   -0.73178505,    -2.28237703,     0.00000000]),  # H
    vq.Atom( 1, [   -5.89039118,    -0.02589114,     0.00000000]),  # H
    vq.Atom( 6, [    3.81469348,    -0.09993438,     0.00000000]),  # C
    vq.Atom( 8, [    2.74426008,    -2.16115489,     0.00000000]),  # O
    vq.Atom( 7, [    2.66029955,     2.15898171,     0.00000000]),  # N
    vq.Atom( 1, [    3.71254812,     3.73605631,     0.00000000]),  # H
    vq.Atom( 1, [    0.73178505,     2.28237703,     0.00000000]),  # H
    vq.Atom( 1, [    5.89039118,     0.02589114,     0.00000000]),  # H
    ],
    charge=0,
    multiplicity=1,
)

basis = vq.BasisSet(mol, "cc-pvtz")

rhf_opts = vq.RHFOptions()
rhf_opts.conv_tol_energy = 1.0e-08
rhf_opts.conv_tol_grad = 1.0e-06
rhf_opts.max_iter = 200
rhf_opts.scf_accelerator = vq.SCFAccelerator.DIIS
rhf_opts.diis_subspace_size = 8
rhf_opts.damping = 0.0
rhf_opts.linear_dep_threshold = 1.0e-07
hf = vq.run_rhf(mol, basis, rhf_opts)
assert hf.converged, f"RHF did not converge: {hf}"

mp2_opts = vq.MP2Options()
mp2_opts.n_frozen_core = 0
mp2_opts.density_fit = False
mp2 = vq.run_mp2(mol, basis, hf, mp2_opts)

result = {
    "system": "s22-04-formamide-dimer",
    "body": "dimer",
    "variant": "mp2",
    "e_hf": hf.energy,
    "e_correlation": mp2.e_correlation,
    "e_total": mp2.e_total,
    "e_os": mp2.e_os,
    "e_ss": mp2.e_ss,
    "n_frozen_core": mp2.n_frozen_core,
    "n_scf_iter": hf.n_iter,
    "scf_converged": hf.converged,
}

out_path = (HERE / STEM).with_suffix(".result")
out_path.write_text(repr(result) + "\n")
print(repr(result))
