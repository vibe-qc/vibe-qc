/** The method catalog rendered at /methods/.
 *
 * One row per user-facing method family, with the status label the manual
 * gives it. The four labels mirror the vocabulary of docs/features.md and
 * docs/experimental/catalog.md:
 *
 *   production    validated within its documented scope and release-gated
 *   preview       reachable and maintained, with a narrower validation
 *                 envelope; the output says which caveat applies
 *   experimental  emits an ExperimentalWarning at runtime; research output,
 *                 not validated for published numbers, not release-gated
 *   gated         fails closed with a scientific message until the missing
 *                 terms are implemented and validated
 *
 * Every `docs` link points at a page that already exists in the published
 * manual (docs/ on the release branch). The site deploys from main while the
 * manual waits for a qualified release, so a link to a page that only exists
 * on main would be dead until then. `tests/methods.verify.mjs` checks the
 * rendered page against this file.
 */
