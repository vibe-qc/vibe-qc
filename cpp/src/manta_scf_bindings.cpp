#include "vibeqc/manta_scf.hpp"
#include <pybind11/pybind11.h>
#include <pybind11/stl.h>

namespace py=pybind11;
void bind_manta_scf(py::module_& m) {
    using namespace vibeqc::manta;
    m.def("_matches_molecular_engine_source",&matches_molecular_engine_source,
          py::arg("molecule"),py::arg("basis"),py::arg("provenance"));
    py::class_<MolecularEngineProvenance>(m,"MolecularEngineProvenance")
        .def_readonly("method",&MolecularEngineProvenance::method)
        .def_readonly("provider_version",&MolecularEngineProvenance::provider_version)
        .def_readonly("functional",&MolecularEngineProvenance::functional)
        .def_readonly("xc_provider",&MolecularEngineProvenance::xc_provider)
        .def_readonly("xc_source_identity",&MolecularEngineProvenance::xc_source_identity)
        .def_readonly("range_exchange_source_identity",&MolecularEngineProvenance::range_exchange_source_identity)
        .def_readonly("channel_batch",&MolecularEngineProvenance::channel_batch)
        .def_readonly("xc_grid_points",&MolecularEngineProvenance::xc_grid_points)
        .def_readonly("vv10_grid_points",&MolecularEngineProvenance::vv10_grid_points)
        .def_readonly("range_exchange_shell_calls",&MolecularEngineProvenance::range_exchange_shell_calls)
        .def_readonly("range_exchange_build_calls",&MolecularEngineProvenance::range_exchange_build_calls)
        .def_readonly("exchange_active",&MolecularEngineProvenance::exchange_active)
        .def_readonly("full_exchange_fraction",&MolecularEngineProvenance::full_exchange_fraction)
        .def_readonly("range_exchange_fraction",&MolecularEngineProvenance::range_exchange_fraction)
        .def_readonly("range_omega",&MolecularEngineProvenance::range_omega)
        .def_readonly("orbital_basis_identity",&MolecularEngineProvenance::orbital_basis_identity)
        .def_readonly("molecule_identity",&MolecularEngineProvenance::molecule_identity)
        .def_readonly("requested_backend",&MolecularEngineProvenance::requested_backend)
        .def_readonly("one_electron_provider",&MolecularEngineProvenance::one_electron_provider)
        .def_readonly("coulomb_provider",&MolecularEngineProvenance::coulomb_provider)
        .def_readonly("exchange_provider",&MolecularEngineProvenance::exchange_provider)
        .def_readonly("coulomb_algorithm",&MolecularEngineProvenance::coulomb_algorithm)
        .def_readonly("confirmation_coulomb_algorithm",&MolecularEngineProvenance::confirmation_coulomb_algorithm)
        .def_readonly("confirmation_coulomb_source_identity",&MolecularEngineProvenance::confirmation_coulomb_source_identity)
        .def_readonly("confirmation_coulomb_build_calls",&MolecularEngineProvenance::confirmation_coulomb_build_calls)
        .def_readonly("bupo_partition_identity",&MolecularEngineProvenance::bupo_partition_identity)
        .def_readonly("bupo_near_provider",&MolecularEngineProvenance::bupo_near_provider)
        .def_readonly("bupo_build_calls",&MolecularEngineProvenance::bupo_build_calls)
        .def_readonly("bupo_order",&MolecularEngineProvenance::bupo_order)
        .def_readonly("bupo_near_shell_calls",&MolecularEngineProvenance::bupo_near_shell_calls)
        .def_readonly("bupo_far_blocks",&MolecularEngineProvenance::bupo_far_blocks)
        .def_readonly("bupo_moment_panels",&MolecularEngineProvenance::bupo_moment_panels)
        .def_readonly("bupo_moment_primitive_pairs",&MolecularEngineProvenance::bupo_moment_primitive_pairs)
        .def_readonly("bupo_integral_tolerance",&MolecularEngineProvenance::bupo_integral_tolerance)
        .def_readonly("bupo_maximum_integral_error",&MolecularEngineProvenance::bupo_maximum_integral_error)
        .def_readonly("bupo_last_j_bound",&MolecularEngineProvenance::bupo_last_j_bound)
        .def_readonly("bupo_setup_wall_seconds",&MolecularEngineProvenance::bupo_setup_wall_seconds)
        .def_readonly("bupo_moment_primitive_products",&MolecularEngineProvenance::bupo_moment_primitive_products)
        .def_readonly("ri_bupo_metric_rank",&MolecularEngineProvenance::ri_bupo_metric_rank)
        .def_readonly("ri_bupo_forward_source_identity",&MolecularEngineProvenance::ri_bupo_forward_source_identity)
        .def_readonly("ri_bupo_adjoint_source_identity",&MolecularEngineProvenance::ri_bupo_adjoint_source_identity)
        .def_readonly("ri_bupo_metric_factor_identity",&MolecularEngineProvenance::ri_bupo_metric_factor_identity)
        .def_readonly("ri_bupo_last_energy_bound",&MolecularEngineProvenance::ri_bupo_last_energy_bound)
        .def_readonly("ri_bupo_last_forward_bound",&MolecularEngineProvenance::ri_bupo_last_forward_bound)
        .def_readonly("ri_bupo_last_adjoint_bound",&MolecularEngineProvenance::ri_bupo_last_adjoint_bound)
        .def_readonly("ri_bupo_last_metric_residual",&MolecularEngineProvenance::ri_bupo_last_metric_residual)
        .def_readonly("ri_bupo_metric_inverse_norm_bound",&MolecularEngineProvenance::ri_bupo_metric_inverse_norm_bound)
        .def_readonly("exchange_algorithm",&MolecularEngineProvenance::exchange_algorithm)
        .def_readonly("one_electron_source_identity",&MolecularEngineProvenance::one_electron_source_identity)
        .def_readonly("coulomb_source_identity",&MolecularEngineProvenance::coulomb_source_identity)
        .def_readonly("exchange_source_identity",&MolecularEngineProvenance::exchange_source_identity)
        .def_readonly("terminal_density_alpha_identity",&MolecularEngineProvenance::terminal_density_alpha_identity)
        .def_readonly("terminal_density_beta_identity",&MolecularEngineProvenance::terminal_density_beta_identity)
        .def_readonly("fallback_reason",&MolecularEngineProvenance::fallback_reason)
        .def_readonly("one_electron_shell_calls",&MolecularEngineProvenance::one_electron_shell_calls)
        .def_readonly("jk_shell_calls",&MolecularEngineProvenance::jk_shell_calls)
        .def_readonly("jk_build_calls",&MolecularEngineProvenance::jk_build_calls)
        .def_readonly("primitive_integrals_evaluated",&MolecularEngineProvenance::primitive_integrals_evaluated)
        .def_readonly("integral_modeled_peak_bytes",&MolecularEngineProvenance::integral_modeled_peak_bytes)
        .def_readonly("primitive_evaluations_measured",&MolecularEngineProvenance::primitive_evaluations_measured)
        .def_readonly("full_build_confirmed",&MolecularEngineProvenance::full_build_confirmed)
        .def_readonly("stationarity_confirmed",&MolecularEngineProvenance::stationarity_confirmed)
        .def_readonly("terminal_energy_delta",&MolecularEngineProvenance::terminal_energy_delta)
        .def_readonly("terminal_fock_delta",&MolecularEngineProvenance::terminal_fock_delta)
        .def_readonly("terminal_commutator_norm",&MolecularEngineProvenance::terminal_commutator_norm)
        .def_readonly("one_electron_wall_seconds",&MolecularEngineProvenance::one_electron_wall_seconds)
        .def_readonly("jk_wall_seconds",&MolecularEngineProvenance::jk_wall_seconds);
    py::class_<MolecularHFEngine>(m,"_MolecularHFEngine")
        .def(py::init<>())
        .def_readwrite("backend",&MolecularHFEngine::backend)
        .def_readwrite("coulomb",&MolecularHFEngine::coulomb)
        .def_readwrite("exchange",&MolecularHFEngine::exchange)
        .def_readwrite("budget",&MolecularHFEngine::budget)
        .def_readwrite("ri",&MolecularHFEngine::ri)
        .def_readwrite("bupo",&MolecularHFEngine::bupo)
        .def_readwrite("ri_bupo",&MolecularHFEngine::ri_bupo)
        .def_readwrite("channel_batch",&MolecularHFEngine::channel_batch);
    m.def("_run_rhf",&run_rhf_with_engine,py::arg("molecule"),py::arg("basis"),py::arg("options"),
          py::arg("engine"),py::arg("auxiliary")=nullptr,py::call_guard<py::gil_scoped_release>());
    m.def("_run_uhf",&run_uhf_with_engine,py::arg("molecule"),py::arg("basis"),py::arg("options"),
          py::arg("engine"),py::arg("auxiliary")=nullptr,py::call_guard<py::gil_scoped_release>());
    m.def("_run_rks",&run_rks_with_engine,py::arg("molecule"),py::arg("basis"),py::arg("options"),
          py::arg("engine"),py::arg("auxiliary")=nullptr,py::call_guard<py::gil_scoped_release>());
    m.def("_run_uks",&run_uks_with_engine,py::arg("molecule"),py::arg("basis"),py::arg("options"),
          py::arg("engine"),py::arg("auxiliary")=nullptr,py::call_guard<py::gil_scoped_release>());

}
