// Per-element parameter tables for the EEQ atomic-charge model.
//
// Data origin:
//
//   * χ (electronegativity), η (chemical hardness), κχ (CN scaling),
//     γ (Gaussian width) — Z = 1..103. From Caldeweyher, Ehlert,
//     Hansen, Neugebauer, Spicher, Bannwarth, Grimme, J. Chem. Phys.
//     150, 154122 (2019), supporting information, Table S2 (fitted
//     parameters of the EEQ-2019 charge model).
//
//   * R_cov — covalent radii in bohr from
//     P. Pyykkö & M. Atsumi, Chem. Eur. J. 15, 188-197 (2009).
//     The published values are in Ångström; we store them here in
//     bohr (× 1.8897261246 bohr/Å exactly) so the CN counting can
//     consume them without per-call unit conversion.
//
// Each row carries the four EEQ parameters + the covalent radius for
// one element, indexed by atomic number. We keep the table as an
// array of small structs (one row per element) rather than four
// parallel arrays — slightly worse cache locality for any single
// scan, but much harder to mis-align when adding / editing rows.
//
// Numerical values are scientific facts from published sources and
// are not subject to expressive copyright. The choice of layout
// (struct-of-element, indexed by Z, bohr-units pre-conversion) is
// vibe-qc's own.

#include "vibeqc/eeq_charges.hpp"

