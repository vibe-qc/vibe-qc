#!/usr/bin/env python3
"""One-time migration: regenerate every bundled QVF-Basis record from the
tracked ``.g94`` / ``.ecp`` text and seed its 1.1.0 provenance (#406, #407).

Run once on 2026-10-11 to turn the records into the source of truth. Kept as
the record of how the 255 records' provenance was seeded; it is not part of
any pipeline and must not be run against a library whose records already
carry provenance (it would overwrite curated edits with the mechanical
derivation below).

What it derives, per record ``<stem>``:

* **content** from ``basis/<stem>.g94`` and ``basis/<stem>.ecp``, the text
  libint and libecpint actually read, parsed by the toolkit's G94 importer.
  Fifteen records (the Pople sets and STO-6G) had been generated by an
  earlier importer that stored SP shells interleaved and were never
  regenerated; the text is the side every result was computed with.
* **name** = the file stem (254 records carried the placeholder
  ``<g94-import>``).
* **role** from ``registry.toml``'s family patterns (fitting sets).
* **description** = the tracked header prose, minus decorative rules and
  the retired splitter's boilerplate, so no curated note is lost.
* **references** from ``[routes.basis_sets]`` in the citation database and
  from DOIs in the header; a DOI the database does not know becomes a
  reference keyed ``doi:<doi>`` carrying the header line that named it.
* **provenance.kind / upstream**: ``vendor`` for a file byte-identical to
  libint 2.13.1's bundle, for libint files completed with Basis Set
  Exchange blocks, and for the Bredow-group pob sets; ``bse`` otherwise.
* **provenance.retrieval_date** from a date in the header, else the date
  the file entered this repository's history.
* **provenance.citations**: one route over all elements, except the pob
  sets and the def2 family, whose ranges come from the per-range tables
  below (#288).

Usage::

    python scripts/basisset_dev/seed_qvf_records_1_1.py          # dry run
    python scripts/basisset_dev/seed_qvf_records_1_1.py --write
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "scripts"))
from render_basis_library import load_toolkit  # noqa: E402

LIBRARY = REPO / "python" / "vibeqc" / "basis_library"
BASIS_DIR = LIBRARY / "basis"
QVF_DIR = LIBRARY / "qvf"
DATABASE = REPO / "python" / "vibeqc" / "output" / "citations" / "database.toml"
REGISTRY = LIBRARY / "registry.toml"
BREDOW_URL = "https://www.chemie.uni-bonn.de/bredow/de/software"
BSE_URL = "https://www.basissetexchange.org"

_DOI_RE = re.compile(r"10\.\d{4,9}/[^\s;,)\]]+")
_DATE_RE = re.compile(r"(20\d\d-\d\d-\d\d)")
_BSE_VERSION_RE = re.compile(r"(?:catalogue version|BSE v|Version|version)\s*v?(\d+\.\d+)", re.IGNORECASE)
_BSE_NAME_RE = re.compile(r"^BSE name:\s*(.+)$", re.IGNORECASE)
_RULE_RE = re.compile(r"^[-=\s]*$")
_SPLITTER_BOILERPLATE = (
    "ECP block(s) split out of",
    "scripts/basisset_dev/split_ecp_g94.py",
)

# Family hints by name prefix. Decorative; the registry decides behaviour.
_FAMILY_PREFIXES = [
    ("sto-", "sto"), ("3-21g", "pople"), ("6-31", "pople"), ("6-311", "pople"),
    ("cc-p", "dunning"), ("aug-cc-p", "dunning"), ("jul-cc-", "dunning"),
    ("jun-cc-", "dunning"), ("augmentation-cc-", "dunning"),
    ("def2-", "ahlrichs"), ("dhf-", "ahlrichs"), ("x2c-", "ahlrichs"),
    ("pob-", "pob"), ("pc-", "jensen"), ("aug-pc-", "jensen"), ("pcs-", "jensen"),
    ("aug-pcs-", "jensen"), ("pcseg-", "jensen"), ("aug-pcseg-", "jensen"),
    ("pcj-", "jensen"), ("ano-", "ano"), ("sapporo-", "sapporo"), ("sarc", "sarc"),
    ("lanl", "lanl"), ("vdzp", "grimme"), ("sadlej", "sadlej"), ("demon-", "demon"),
    ("minix", "minimal"), ("mini", "minimal"), ("cologne-", "cologne"),
]

# Stuttgart-Cologne ECP papers by element, from the def2-ECP distribution
# (the def2 sidecar headers and docs/license.md). pob-TZVP(-rev2) carry the
# same potentials block for block (#228, #207).
_STUTTGART_ECP_RANGES: dict[str, list[str]] = {
    "andrae_ecp_1990": ["Y", "Zr", "Nb", "Mo", "Tc", "Ru", "Rh", "Pd", "Ag", "Cd",
                        "Hf", "Ta", "W", "Re", "Os", "Ir", "Pt", "Au", "Hg"],
    "metz_stoll_dolg_ecp_2000": ["In", "Sn", "Sb", "Tl", "Pb", "Bi"],
    "peterson_pp_2003": ["Te", "I", "Xe", "Po", "At", "Rn"],
    "leininger_nicklass_ecp_1996": ["Rb", "Cs"],
    "kaupp_schleyer_stoll_preuss_ecp_1991": ["Sr", "Ba"],
    "dolg_stoll_savin_preuss_lanthanide_ecp_1989": [
        "La", "Ce", "Pr", "Nd", "Pm", "Sm", "Eu", "Gd", "Tb", "Dy", "Ho", "Er", "Tm", "Yb", "Lu"],
}

# Per-range valence routes (#288, #228). Keys not listed route over every element.
_VALENCE_RANGES: dict[str, dict[str, list[str] | None]] = {
    "pob-tzvp-rev2": {
        "peintinger_pob_tzvp_2013": None,
        "vilela_oliveira_pob_rev2_2019": "H-Br",
        "laun_pob_rev2_fifth_period_2022": "Rb-I",
        "laun_pob_rev2_sixth_period_2021": "Cs-Ba,Hf-Po",
        "seidler_pob_rev2_lanthanides_2023": "La-Lu",
    },
    "pob-tzvp": {
        "peintinger_pob_tzvp_2013": None,
        "laun_pob_fifth_period_2018": "Rb-I",
    },
}


def sh(*args: str) -> str:
    return subprocess.run(args, cwd=REPO, check=True, capture_output=True, text=True).stdout


def libint_basis_dir() -> Path:
    root = REPO / "third_party" / "libint" / "install" / "share" / "libint"
    hits = sorted(root.glob("*/basis"))
    if not hits:
        raise SystemExit(f"libint basis bundle not found under {root}")
    return hits[-1]


def header_lines(path: Path) -> list[str]:
    """The leading ``!`` comment block, prefix stripped."""
    out: list[str] = []
    for line in path.read_text(errors="replace").splitlines():
        if line.startswith("!"):
            out.append(line[1:].rstrip())
            continue
        if line.strip():
            break
    return out


def prose(lines: list[str]) -> list[str]:
    kept: list[str] = []
    for line in lines:
        text = line[1:] if line.startswith(" ") else line
        if _RULE_RE.match(text):
            continue
        if any(marker in text for marker in _SPLITTER_BOILERPLATE):
            continue
        kept.append(text.rstrip())
    while kept and not kept[0].strip():
        kept.pop(0)
    while kept and not kept[-1].strip():
        kept.pop()
    return kept


def first_commit_date(path: Path) -> str:
    out = sh("git", "log", "--diff-filter=A", "--format=%as", "--", str(path.relative_to(REPO)))
    dates = out.split()
    return dates[-1] if dates else ""


def author_initials(name: str) -> str:
    if "," in name:
        last, first = [part.strip() for part in name.split(",", 1)]
        initials = " ".join(f"{p[0]}." for p in first.replace("-", " ").split() if p)
        return f"{initials} {last}".strip()
    return name


def entry_description(entry: dict) -> str:
    authors = ", ".join(author_initials(a) for a in entry.get("authors", []))
    venue = entry.get("journal") or entry.get("title") or ""
    parts = [p for p in (authors, venue) if p]
    text = ", ".join(parts)
    if entry.get("volume"):
        text += f" {entry['volume']}"
    if entry.get("pages"):
        text += f", {str(entry['pages']).replace('--', '-')}"
    if entry.get("year"):
        text += f" ({entry['year']})"
    return text


def expand_range(spec: str | None, symbols_by_z: dict[int, str], z_of: dict[str, int]) -> list[str] | None:
    if spec is None:
        return None
    out: list[str] = []
    for piece in spec.split(","):
        a, _, b = piece.partition("-")
        if b:
            out.extend(symbols_by_z[z] for z in range(z_of[a], z_of[b] + 1))
        else:
            out.append(a)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="write the records (default: dry run)")
    args = parser.parse_args(argv)

    tk = load_toolkit()
    m = tk.model
    from_g94 = tk.importer_g94.from_g94
    z_of = tk._element_data.ATOMIC_NUMBER
    symbols_by_z = tk._element_data.SYMBOL

    db = tomllib.loads(DATABASE.read_text())
    routes: dict[str, list[str]] = db["routes"]["basis_sets"]
    entries: dict[str, dict] = db["entries"]
    entry_by_doi = {str(e["doi"]).lower(): k for k, e in entries.items() if e.get("doi")}
    registry = tomllib.loads(REGISTRY.read_text())
    families = [(re.compile(f["pattern"]), f.get("role", "orbital")) for f in registry["families"]]
    libint_dir = libint_basis_dir()
    libint_version = libint_dir.parent.name
    libint_names = {p.name for p in libint_dir.glob("*.g94")}

    counts = {"vendor": 0, "bse": 0, "refs": 0, "unknown_doi": 0}
    for g94 in sorted(BASIS_DIR.glob("*.g94")):
        stem = g94.stem
        text = g94.read_text(encoding="utf-8")
        data = from_g94(text, name=stem)
        ecp_path = g94.with_suffix(".ecp")
        ecp_lines: list[str] = []
        if ecp_path.is_file():
            ecp_data = from_g94(ecp_path.read_text(encoding="utf-8"), name=stem, role="ecp")
            merged = dict(data.ecps or {})
            merged.update(ecp_data.ecps or {})
            data.ecps = merged or None
            for sym, element in data.elements.items():
                element.ecp_id = sym if sym in merged else None
            ecp_lines = prose(header_lines(ecp_path))

        # role and family
        role = "orbital"
        for pattern, fam_role in families:
            if pattern.search(stem):
                role = fam_role
                break
        data.role = m.BasisRole(role)
        data.basis_family = next((fam for prefix, fam in _FAMILY_PREFIXES if stem.startswith(prefix)), None)

        # description: tracked header prose, orbital then sidecar
        head = header_lines(g94)
        description = prose(head)
        if ecp_lines:
            description += ["", "ECP sidecar:"] + ecp_lines
        data.description = "\n".join(description)

        # references
        keys = list(routes.get(stem, []))
        header_text = "\n".join(head + ecp_lines)
        dois = []
        for doi in _DOI_RE.findall(header_text):
            doi = doi.rstrip(".").lower()
            if doi not in dois:
                dois.append(doi)
        refs: list = []
        seen_keys: set[str] = set()
        for key in keys:
            entry = entries[key]
            refs.append(m.Reference(key=key, description=entry_description(entry), doi=entry.get("doi")))
            seen_keys.add(key)
        for doi in dois:
            key = entry_by_doi.get(doi)
            if key is not None:
                if key not in seen_keys:
                    entry = entries[key]
                    refs.append(m.Reference(key=key, description=entry_description(entry), doi=entry.get("doi")))
                    seen_keys.add(key)
                    keys.append(key)
                continue
            line = next((l.strip() for l in header_text.splitlines() if doi in l.lower()), "")
            line = re.sub(r"\s*;?\s*DOI:?\s*10\.\S+", "", line, flags=re.IGNORECASE).strip(" ;:-")
            for prefix in ("Originating publication:", "Cite:", "Citation:", "Reference:"):
                if line.lower().startswith(prefix.lower()):
                    line = line[len(prefix):].strip()
            refs.append(m.Reference(key=f"doi:{doi}", description=line, doi=doi))
            counts["unknown_doi"] += 1
        data.references = refs
        counts["refs"] += bool(refs)

        # citation routes
        citations: list = []
        valence_ranges = _VALENCE_RANGES.get(stem)
        present = set(data.elements) | set(data.ecps or {})
        for key in keys:
            if valence_ranges is not None and key in valence_ranges:
                elements = expand_range(valence_ranges[key], symbols_by_z, z_of)
            elif key in _STUTTGART_ECP_RANGES and data.ecps:
                elements = [s for s in _STUTTGART_ECP_RANGES[key] if s in data.ecps]
                if not elements:
                    elements = None
            else:
                elements = None
            if elements is not None:
                elements = [s for s in elements if s in present]
                if not elements:
                    continue
            citations.append(m.CitationRoute(keys=[key], elements=elements))
        # merge routes with identical element coverage
        merged_routes: dict[tuple, list[str]] = {}
        for route in citations:
            cover = tuple(route.elements) if route.elements is not None else ("*",)
            merged_routes.setdefault(cover, []).extend(route.keys)
        citations = [
            m.CitationRoute(keys=ks, elements=None if cover == ("*",) else list(cover))
            for cover, ks in merged_routes.items()
        ]

        # provenance
        dates = _DATE_RE.findall(header_text)
        retrieval = min(dates) if dates else first_commit_date(g94)
        notes = None if dates else "The date is when the file entered this repository's history; the import date was not recorded."
        upstream: list = []
        identical = g94.name in libint_names and (libint_dir / g94.name).read_bytes() == g94.read_bytes()
        bse_version = None
        if (mv := _BSE_VERSION_RE.search(header_text)):
            bse_version = mv.group(1)
        bse_name = None
        for line in header_text.splitlines():
            if (mn := _BSE_NAME_RE.match(line.strip())):
                bse_name = mn.group(1).strip()
                break
        if identical:
            kind = m.ProvenanceKind.VENDOR
            upstream.append(m.Upstream(name="libint", version=libint_version, identifier=stem,
                                       detail="byte-identical to libint's bundled file"))
        elif g94.name in libint_names:
            kind = m.ProvenanceKind.VENDOR
            upstream.append(m.Upstream(name="libint", version=libint_version, identifier=stem,
                                       detail="libint's element blocks, unchanged"))
            upstream.append(m.Upstream(name="basis-set-exchange", version=bse_version, url=BSE_URL,
                                       identifier=bse_name or stem,
                                       detail="element blocks libint omits, merged as reviewed imports"))
        elif stem.startswith("pob-"):
            kind = m.ProvenanceKind.VENDOR
            source_dir = {"pob-tzvp": "pob-TZVP", "pob-tzvp-rev2": "pob-TZVP-rev2", "pob-dzvp-rev2": "pob-DZVP-rev2"}[stem]
            upstream.append(m.Upstream(name="Bredow group basis-set archive", url=BREDOW_URL, identifier=source_dir,
                                       detail=f"per-element CRYSTAL records under basis_library/sources/{source_dir}/"))
            if stem == "pob-dzvp-rev2":
                upstream.append(m.Upstream(name="basis-set-exchange", version="0.12", url=BSE_URL, identifier="pob-DZVP-rev2",
                                           detail="Si, Cr-Br, checked against the archive-derived records"))
        else:
            kind = m.ProvenanceKind.BSE
            upstream.append(m.Upstream(name="basis-set-exchange", version=bse_version, url=BSE_URL,
                                       identifier=bse_name or stem))
        counts[kind.value] += 1
        data.provenance = m.Provenance(
            origin="file", kind=kind, upstream=upstream, retrieval_date=retrieval or None,
            citations=citations, notes=notes,
        )
        if args.write:
            tk.library.save_record(data, QVF_DIR / f"{stem}{tk.library.RECORD_SUFFIX}")
    print(f"{'wrote' if args.write else 'would write'} {sum(1 for _ in BASIS_DIR.glob('*.g94'))} records: {counts}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
