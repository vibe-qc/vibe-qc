def _is_tight_cell(system: PeriodicSystem) -> bool:
    """Return True if the cell is tight enough that image-cell AO overlap
    is non-negligible -- i.e., the molecular DensityFitting J is
    inaccurate.  Heuristic from pbc_gdf.py: Z>1 + cell_vol < 500 bohr^3.
    """
    if int(system.dim) != 3:
        return False
    z_max = max(atom.Z for atom in system.unit_cell)
    if z_max <= 1:
        return False  # pure hydrogen -- compcell handles it, but molecular DF is fine
    cell_vol = float(abs(np.linalg.det(np.asarray(system.lattice))))
    return cell_vol < 500.0


def _clone_lat_opts(src: LatticeSumOptions, **overrides) -> LatticeSumOptions:
    """Return a field-wise copy of ``src`` with ``overrides`` applied."""
    dst = LatticeSumOptions()
    for attr in dir(src):
        if attr.startswith("_"):
            continue
        try:
            value = getattr(src, attr)
        except Exception:
            continue
        if callable(value):
            continue
        try:
            setattr(dst, attr, value)
        except Exception:
            pass
    for attr, value in overrides.items():
        setattr(dst, attr, value)
    return dst


def _home_cell_electrostatics_lat_opts(
    src: LatticeSumOptions,
) -> tuple[LatticeSumOptions, LatticeSumOptions]:
    """Lattice options for the molecular-limit (vacuum-padded) J/K model.

    The molecular-limit RIJCOSX path builds J with the *molecular*
    density-fitting builder, i.e. from the home-cell electrons only.
    In periodic boundary conditions only the total electrostatic
    energy of a neutral cell is well defined; its nuclear-nuclear,
    electron-nuclear and electron-electron image sums individually
    diverge (or, truncated, are O(sum_g 1/|g|)) and cancel only when
    they are evaluated over the same set of image cells (Makov & Payne,
    Phys. Rev. B 51, 4014 (1995), Sec. II; the neutral localized
    system's residual after that cancellation is the multipole tail,
    O(L^-3) and below). Dropping the image electrons alone therefore
    leaves the bare monopole sums -0.5 sum_g sum_AB Z_A Z_B / |R_AB + g|
    in the one-electron terms, and the image-ket exchange class
    sum_g (mu lambda | nu_g sigma_g) -- for a Gamma Bloch orbital the
    electron's Coulomb interaction with its own images, which pairs
    with the image part of J -- in K. Both were present before #707.

    Returns ``(one_electron_opts, exchange_opts)``:

    * ``one_electron_opts`` restricts the nuclear-attraction and
      nuclear-repulsion lattice sums to the home-cell nuclei
      (``nuclear_cutoff_bohr = 0`` selects exactly the zero cell) while
      keeping the ket-image overlap classes of V_ne consistent with the
      S and T lattice sums;
    * ``exchange_opts`` restricts the COSX K image-cell list to the
      home cell (``cutoff_bohr = 0``).

    Within the envelope (every active length >= 12 bohr, no tight
    cell) the neglected image terms are the same neutral-cell multipole
    tail the molecular DF J already neglects, so the path reproduces
    the molecular RIJCOSX oracle independently of the box length and of
    the user's lattice cutoffs (regression:
    ``test_rijcosx_gamma_vacuum_padded_home_cell_electrostatics``).
    """
    one_electron = _clone_lat_opts(src, nuclear_cutoff_bohr=0.0)
    exchange = _clone_lat_opts(src, cutoff_bohr=0.0)
    return one_electron, exchange


from .guess import periodic_guess_capabilities

_RIJCOSX_GUESSES = periodic_guess_capabilities("rijcosx")


def _rijcosx_guess(opts, *, driver):
    """Compatibility selector query using the same explicit capability set."""
    return _coerce_periodic_driver_guess(
        getattr(opts, "initial_guess", InitialGuess.AUTO),
        driver=driver, supported=_RIJCOSX_GUESSES,
    )


def _rijcosx_selection(system, opts, *, driver, open_shell):
    from .guess import select_initial_guess
    from .pbc_gdf import _refuse_ecp_options

    _refuse_ecp_options(opts, driver, system=system)

    from .guess import coerce_initial_guess
    requested = coerce_initial_guess(getattr(opts, "initial_guess", InitialGuess.AUTO))
    if requested == InitialGuess.READ and not getattr(opts, "read_path", ""):
        names = ("read_density_alpha", "read_density_beta") if open_shell else ("read_density",)
        if not all(np.asarray(getattr(opts, name, [])).size for name in names):
            raise ValueError(f"{driver}: READ requires a complete density payload or read_path")
    return select_initial_guess(
        system.unit_cell_molecule(), requested,
        is_periodic=True, is_open_shell=open_shell,
        supported=_RIJCOSX_GUESSES,
        atomic_spins=getattr(opts, "atomic_spins", None), driver=driver,
    )


def _initial_density_closed(system, basis, n_occ, guess, lat_opts, overlap, options=None):
    """Build a shared-framework Gamma density for a RIJCOSX route."""
    if guess == InitialGuess.PATOM:
        # The native preparation seam has the actual Gamma S/Hcore/JK.
        return np.empty((0, 0))
    density = initial_density_closed_shell(
        system.unit_cell_molecule(),
        basis,
        int(n_occ),
        guess,
        is_periodic=True,
        periodic_system=system,
        lattice_opts=lat_opts,
        overlap=overlap,
        read_density=getattr(options, "read_density", None),
        read_path=getattr(options, "read_path", ""),
    )
    # The C++ JK-loop APIs use an empty matrix to request their established
    # Hcore diagonalisation. Every other supported kind produces a density.
    return np.empty((0, 0)) if density is None else density


def _initial_densities_open(
    system, basis, n_alpha, n_beta, guess, lat_opts, overlap, atomic_spins=None, options=None
):
    """Build shared-framework Gamma spin densities for RIJCOSX."""
    if guess == InitialGuess.PATOM:
        return np.empty((0, 0)), np.empty((0, 0))
    densities = initial_densities_open_shell(
        system.unit_cell_molecule(),
        basis,
        int(n_alpha),
        int(n_beta),
        guess,
        is_periodic=True,
        periodic_system=system,
        lattice_opts=lat_opts,
        overlap=overlap,
        atomic_spins=atomic_spins,
        read_density_alpha=getattr(options, "read_density_alpha", None),
        read_density_beta=getattr(options, "read_density_beta", None),
        read_path=getattr(options, "read_path", ""),
    )
    if densities is None:
        empty = np.empty((0, 0))
        return empty, empty.copy()
    return densities


def _validate_atomic_spins(opts, guess):
    """Keep ATOMSPIN coupled to the resolved SAD seed."""
    if getattr(opts, "atomic_spins", None) and guess != InitialGuess.SAD:
        raise RuntimeError(
            "GuessEngine: atomic_spins (ATOMSPIN broken-symmetry seed) "
            f"requires the SAD guess; resolved guess is {guess.name}"
        )


