def _vacuum_envelope_setup(system, basis, aux_basis, lat_opts, label, plog):
    """Shared vacuum-padded-envelope validation + one-electron setup.

    Raises ``NotImplementedError`` outside the envelope (same criterion
    as the Gamma-RKS rung: every active lattice length >= 12 bohr and
    not a tight cell); returns ``(mol, aux, S, Hcore, E_nuc,
    exchange_lat_opts)``. V_ne and E_nuc carry the home-cell nuclei
    only and ``exchange_lat_opts`` restricts the COSX K to the home
    cell, matching the molecular DF J (#707; see
    ``_home_cell_electrostatics_lat_opts``).
    """
    _MIN_ACTIVE_LENGTH_BOHR = 12.0
    tight = _is_tight_cell(system)
    active_lengths = [
        float(np.linalg.norm(np.asarray(system.lattice, dtype=float)[:, i]))
        for i in range(int(system.dim))
    ]
    if tight or min(active_lengths) < _MIN_ACTIVE_LENGTH_BOHR:
        raise NotImplementedError(
            f"{label}: Gamma RIJCOSX open-shell/KS routes are implemented "
            "for the vacuum-padded (molecular-limit) envelope only "
            f"(every active lattice length >= "
            f"{_MIN_ACTIVE_LENGTH_BOHR:.0f} bohr and not a tight cell). "
            "Use the true multi-k GDF/COSX backend (kpoints with >= 2 "
            "points) or the GDF routes."
        )
    mol = system.unit_cell_molecule()
    aux = _resolve_aux_basis(mol, basis, aux_basis)
    one_e_lat_opts, exchange_lat_opts = _home_cell_electrostatics_lat_opts(
        lat_opts
    )
    with plog.stage("integrals_lattice"):
        S_set = compute_overlap_lattice(basis, system, lat_opts)
        T_set = compute_kinetic_lattice(basis, system, lat_opts)
        V_set = compute_nuclear_lattice_dispatch(basis, system, one_e_lat_opts)
    S = _fold_gamma_real(S_set)
    Hcore = _fold_gamma_real(T_set) + _fold_gamma_real(V_set)
    E_nuc = nuclear_repulsion_per_cell(system, one_e_lat_opts)
    return mol, aux, S, Hcore, E_nuc, exchange_lat_opts


def _spin_counts(system, label):
    n_elec = system.n_electrons()
    mult = int(system.multiplicity)
    if mult < 1:
        raise ValueError(f"{label}: multiplicity must be >= 1, got {mult}")
    if (n_elec + mult - 1) % 2 != 0:
        raise ValueError(
            f"{label}: n_electrons={n_elec} and multiplicity={mult} "
            "cannot be split into integer a/b occupations."
        )
    n_alpha = (n_elec + mult - 1) // 2
    n_beta = (n_elec - mult + 1) // 2
    if n_beta < 0:
        raise ValueError(
            f"{label}: multiplicity={mult} exceeds n_electrons={n_elec}"
        )
    return n_alpha, n_beta


def run_periodic_rijcosx_uhf(
    system: PeriodicSystem,
    basis: BasisSet,
    options=None,
    *,
    aux_basis: Optional[str] = None,
    progress: Union[bool, ProgressLogger, None] = None,
):
    """Γ-only periodic UHF via RIJCOSX -- vacuum-padded envelope only.

    The open-shell sibling of :func:`run_periodic_rijcosx_rhf`,
    restricted to the molecular-limit regime (same criterion as the
    Gamma-RKS rung): molecular DF J from the total density + per-spin
    home-cell COSX K through the dedicated Gamma builder, SCF through
    the production C++ ``run_uhf_scf_with_jk`` (per-spin
    post-convergence one-center replacement through the builder hook).
    Spin counts follow ``system.multiplicity``. Tight or short-axis
    cells fail closed.
    """
    from . import UHFOptions, run_uhf_scf_with_jk

    opts = options if options is not None else PeriodicRHFOptions()
    selection = _rijcosx_selection(
        system, opts, driver="run_periodic_rijcosx_uhf", open_shell=True,
    )
    guess = selection.effective
    _validate_atomic_spins(opts, guess)
    lat_opts: LatticeSumOptions = opts.lattice_opts
    plog = resolve_progress(progress)
    label = "run_periodic_rijcosx_uhf"
    n_alpha, n_beta = _spin_counts(system, label)

    mol, aux, S, Hcore, E_nuc, exchange_lat_opts = _vacuum_envelope_setup(
        system, basis, aux_basis, lat_opts, label, plog
    )
    plog.info(
        f"UHF Γ-only RIJCOSX (vacuum-padded envelope) / aux={aux.name}, "
        f"n_alpha={n_alpha}, n_beta={n_beta}"
    )
    with plog.stage("rijcosx_builder"):
        jk = make_periodic_gamma_cosx_jk_builder(
            basis, aux, system, exchange_lat_opts
        )

    with plog.stage("scf"):
        uhf_opts = UHFOptions()
        uhf_opts.initial_guess = selection.requested
        uhf_opts.max_iter = int(opts.max_iter)
        uhf_opts.conv_tol_energy = float(opts.conv_tol_energy)
        uhf_opts.conv_tol_grad = float(getattr(opts, "conv_tol_grad", 1e-6))
        uhf_opts.damping = float(opts.damping)
        uhf_opts.use_diis = bool(opts.use_diis)
        uhf_opts.diis_start_iter = int(opts.diis_start_iter)
        uhf_opts.diis_subspace_size = int(opts.diis_subspace_size)
        init_alpha, init_beta = _initial_densities_open(
            system,
            basis,
            n_alpha,
            n_beta,
            guess,
            lat_opts,
            atomic_spins=getattr(opts, "atomic_spins", None) or None,
            overlap=S, options=opts,
        )
        res = run_uhf_scf_with_jk(
            basis, n_alpha, n_beta, S, Hcore, E_nuc, jk, uhf_opts,
            init_alpha, init_beta,
            molecule=system.unit_cell_molecule(), guess_selection=selection,
        )

    result = SimpleNamespace(
        overlap=np.asarray(S).copy(), hcore=np.asarray(Hcore).copy(),
        restart_lattice=np.asarray(system.lattice).copy(),
        restart_kpoints=np.zeros((1, 3)), restart_weights=np.ones(1),
        restart_basis=res.restart_basis,
        guess_selection=res.guess_selection,
        energy=res.energy,
        e_electronic=res.e_electronic,
        e_nuclear=E_nuc,
        n_iter=res.n_iter,
        converged=res.converged,
        s_squared=float(getattr(res, "s_squared", 0.0)),
        mo_energies_alpha=res.mo_energies_alpha,
        mo_energies_beta=res.mo_energies_beta,
        mo_coeffs_alpha=res.mo_coeffs_alpha,
        mo_coeffs_beta=res.mo_coeffs_beta,
        density_alpha=res.density_alpha,
        density_beta=res.density_beta,
        fock_alpha=res.fock_alpha,
        fock_beta=res.fock_beta,
        scf_trace=res.scf_trace,
        omega=0.0,
        grid_shape=(0, 0, 0),
    )
    plog.info(f"SCF {'converged' if result.converged else 'NOT converged'}")
    plog.info(f"  E_total = {result.energy:.10f} Ha")
    return result


