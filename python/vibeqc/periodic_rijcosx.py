def _resolve_aux_basis(mol, basis: BasisSet, aux_basis: Optional[str]) -> BasisSet:
    """Return an auxiliary basis for the RI-J piece."""
    aux_name = aux_basis or default_aux_for(basis.name)
    aux = make_aux_basis_set(mol, aux_name=aux_name)
    if aux is None:
        raise ValueError(
            f"periodic_rijcosx: no auxiliary basis found for "
            f"{basis.name!r} (tried aux={aux_name!r}). "
            f"Set ri_j_aux_basis explicitly or add a default in "
            f"aux_basis.py:default_aux_for()."
        )
    return aux


