"""Periodic RIJCOSX SCF driver for Γ-only RHF.

M3: Periodic-correct GDF J (compcell/RSGDF Lpq) + periodic COSX K.
M3a: COSX K sums exchange over the truncated image-cell list -- the
home-bra -> image-ket 1/R exchange class (measured on the H-chain
anchor: ||K|| 1.74 -> 3.94 at D = I).  This is exact for vacuum-padded
cells and a first-order image correction for tight cells; it is NOT
yet the Γ-folded GDF exchange (||K_GDF|| = 16.16 on the same anchor),
which additionally contains the long-range classes generated by the
Γ-only density coupling all cell pairs.  See handovers/HANDOVER_RIJCOSX_M3A.md
Sec. "M3a measured outcome".

Architecture (tight-cell path, default for dim=3 with compact cells):
  1. One-electron integrals: Ewald-3D gauge for 3D, bare lattice sum
     for dim < 3, Γ-folded.
  2. Lpq tensor: built once via ``build_lpq_compcell`` (Sun 2017
     compensated charges + AFT correction). Alternative:
     ``build_lpq_native_fft`` (all-FT Bloch pair-FT) via
     ``gdf_method='rsgdf'``.
  3. JKBuilder: C++ ``PeriodicTightCellCOSXJKBuilder``
     - build_J(D): GDF contraction from Lpq (periodic-correct)
     - build_K(D): periodic COSX on Becke grid, exchange summed over
       image cells within ``lattice_opts.cutoff_bohr`` (M3a;
       single-lattice-sum model -- see module docstring caveat)
     - No exxdiv='ewald' Madelung K-shift (COSX-K is a real-space
       direct-truncated sum)
  4. SCF loop: delegates to ``run_rhf_scf_with_jk`` (production C++
     engine).

Molecular-limit path (vacuum-padded cells, large box):
  Uses ``PeriodicGammaCOSXJKBuilder`` (molecular DensityFitting J +
  home-cell COSX K).  This is the M2 path -- faster setup, correct when
  image-cell AO overlap is negligible.  Every electrostatic term of
  this path is evaluated over the home cell alone: the molecular DF J
  carries no image electrons, so V_ne and E_nuc carry no image nuclei
  and the COSX K carries no image-ket exchange class (see
  ``_home_cell_electrostatics_lat_opts``).  Before #707 the three
  one-electron / exchange terms kept their own image truncations
  (``nuclear_cutoff_bohr`` for V_ne and E_nuc, ``cutoff_bohr`` for K)
  while J had none, and every box shorter than those cutoffs was
  over-bound by the uncompensated bare monopole sums (H atom / STO-3G,
  12-bohr box: -1.6377 Ha instead of -0.4666 Ha).

Reference: handovers/HANDOVER_RIJCOSX_M3A.md (M3a milestone; M3 history in
handovers/HANDOVER_RIJCOSX_PBC.md).
"""

