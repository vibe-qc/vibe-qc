def run_periodic_rijcosx_rhf(
    system: PeriodicSystem,
    basis: BasisSet,
    options: Optional[PeriodicRHFOptions] = None,
    *,
    aux_basis: Optional[str] = None,
    gdf_method: str = "compcell",
    compcell_eta: float = 1.0,
    apply_aft_correction: bool = True,
    aft_precision: float = 1e-10,
    aft_ft_convention: str = "libint",
    rcut_strategy: Optional[object] = "pyscf_auto",
    rcut_precision: float = 1e-8,
    gdf_linear_dep_threshold: float = 1e-9,
    rsgdf_ke_cutoff: float = 200.0,
    tight_cell: Optional[bool] = None,
    progress: Union[bool, ProgressLogger, None] = None,
) -> RHFResult:
    """Γ-only periodic RHF via RIJCOSX.

    J: GDF (compcell or RSGDF for tight cells; molecular DF for
       vacuum-padded cells).
    K: periodic COSX on a Becke grid, exchange summed over image
       cells within ``options.lattice_opts.cutoff_bohr`` (M3a).

    Parameters
    ----------
    system
        PeriodicSystem with unit cell + lattice.
    basis
        Orbital (primary) basis set.
    options
        PeriodicRHFOptions. If None, defaults are used.
    aux_basis
        Auxiliary basis name for DF-J. Defaults to
        ``default_aux_for(basis.name)``.
    gdf_method
        Lpq builder for the tight-cell path: ``'compcell'`` (default)
        or ``'rsgdf'`` (all-FT Bloch pair-FT).  Ignored when
        ``tight_cell=False``.
    compcell_eta
        Smooth-Gaussian exponent for the compcell compensating basis.
        Default 1.0.  With AFT on, the answer is η-independent.
    apply_aft_correction
        Apply the analytical-Fourier-transform long-range correction
        (default True).  Makes the compcell answer η-independent.
    aft_precision
        G-mesh precision target for the AFT correction (default 1e-10).
    aft_ft_convention
        FT convention: ``'libint'`` (default, vibe-qc native) or
        ``'libcint'`` (PySCF match).
    rcut_strategy
        Lattice cutoff strategy for the compcell construction
        (default ``'pyscf_auto'``).
    rcut_precision
        Precision target for the per-basis cutoff (default 1e-8).
    gdf_linear_dep_threshold
        Aux metric eigenvalue floor for the GDF fit (default 1e-9).
    rsgdf_ke_cutoff
        Kinetic-energy cutoff (Ha) for the RSGDF dense FFT mesh
        (default 200.0).  Only used when ``gdf_method='rsgdf'``.
    tight_cell
        Force tight-cell or molecular-limit path.  ``None`` (default)
        auto-detects: tight when dim=3, Z>1, and cell volume < 500
        bohr^3.
    progress
        Live progress logging.
    """
    opts = options if options is not None else PeriodicRHFOptions()
    selection = _rijcosx_selection(
        system, opts, driver="run_periodic_rijcosx_rhf", open_shell=False,
    )
    guess = selection.effective
    lat_opts: LatticeSumOptions = opts.lattice_opts
    plog = resolve_progress(progress)

    n_elec = system.n_electrons()
    if n_elec % 2 != 0:
        raise ValueError(
            "run_periodic_rijcosx_rhf: closed-shell RHF requires even "
            f"electron count; got {n_elec}"
        )
    if system.multiplicity != 1:
        raise ValueError(
            "run_periodic_rijcosx_rhf: closed-shell RHF requires "
            f"multiplicity=1; got {system.multiplicity}"
        )

    dim = int(system.dim)
    active_lengths = [
        float(np.linalg.norm(np.asarray(system.lattice, dtype=float)[:, i]))
        for i in range(dim)
    ]

    # ---- Auto-detect tight vs molecular-limit -------------------------
    if tight_cell is None:
        tight_cell = _is_tight_cell(system)

    # ---- Auxiliary basis for DF-J / GDF --------------------------------
    mol = system.unit_cell_molecule()
    aux = _resolve_aux_basis(mol, basis, aux_basis)

    plog.info(
        f"RHF Γ-only RIJCOSX M3 / aux={aux.name}, "
        f"cutoff={lat_opts.cutoff_bohr:.2f} bohr, dim={dim}D, "
        f"tight_cell={tight_cell}, gdf_method={gdf_method}"
    )
    plog.info(
        f"orbital basis: {basis.name}  ({basis.nbasis} BFs / {basis.nshells} shells)"
    )
    plog.info(f"aux basis:     {aux.name}  ({aux.nbasis} BFs / {aux.nshells} shells)")
    plog.info(
        f"periodicity: dim={dim}D, active lengths="
        + ", ".join(f"{x:.3f}" for x in active_lengths)
        + " bohr"
    )

    # ---- One-electron integrals (gauge-consistent with J build) ---------
    # For 3D tight cells with GDF J (which drops G=0), V_ne and E_nuc
    # must also be in the Ewald-3D gauge.  For dim<3, the bare lattice
    # sum is correct.
    # For the molecular-limit path the molecular DF J carries no image
    # electrons, so V_ne / E_nuc must carry no image nuclei and K no
    # image-ket exchange (#707; see _home_cell_electrostatics_lat_opts).
    if tight_cell:
        gauge_lat_opts = _gauge_lat_opts_ewald_3d(lat_opts, system)
        exchange_lat_opts = lat_opts
    else:
        gauge_lat_opts, exchange_lat_opts = _home_cell_electrostatics_lat_opts(
            lat_opts
        )
    if tight_cell and int(system.dim) == 3 and gauge_lat_opts is not lat_opts:
        plog.info(
            "V_ne / e_nuc gauge: Ewald-3D (forced for 3D tight-cell GDF J consistency)"
        )

    with plog.stage("integrals_lattice"):
        S_set = compute_overlap_lattice(basis, system, lat_opts)
        T_set = compute_kinetic_lattice(basis, system, lat_opts)
        V_set = compute_nuclear_lattice_dispatch(basis, system, gauge_lat_opts)

    S = _fold_gamma_real(S_set)
    T = _fold_gamma_real(T_set)
    V_ne = _fold_gamma_real(V_set)
    Hcore = T + V_ne
    E_nuc = nuclear_repulsion_per_cell(system, gauge_lat_opts)

    plog.info(
        f"Γ-folded one-electron matrices: "
        f"{basis.nbasis} x {basis.nbasis}, "
        f"cell cutoff = {lat_opts.cutoff_bohr:.2f} bohr"
    )

    # ---- Build Lpq for tight-cell GDF J ---------------------------------
    if tight_cell:
        with plog.stage("gdf_lpq", detail=f"{gdf_method} aux={aux.nbasis}"):
            if gdf_method == "compcell":
                Lpq = build_lpq_compcell(
                    system,
                    basis,
                    aux,
                    molecule=mol,
                    lat_opts=lat_opts,
                    linear_dep_thr=float(gdf_linear_dep_threshold),
                    compcell_eta=float(compcell_eta),
                    apply_aft_correction=bool(apply_aft_correction),
                    aft_precision=float(aft_precision),
                    aft_ft_convention=str(aft_ft_convention),
                    rcut_strategy=rcut_strategy,
                    rcut_precision=float(rcut_precision),
                )
            elif gdf_method == "rsgdf":
                aux_modrho = make_modrho_aux_basis(aux, mol)
                Lpq = build_lpq_native_fft(
                    system,
                    basis,
                    aux_modrho,
                    ke_cutoff=float(rsgdf_ke_cutoff),
                    lat_opts=lat_opts,
                    linear_dep_thr=float(gdf_linear_dep_threshold),
                )
            else:
                raise ValueError(
                    f"run_periodic_rijcosx_rhf: gdf_method must be "
                    f"'compcell' or 'rsgdf'; got {gdf_method!r}"
                )
        plog.info(
            f"Lpq: {Lpq.shape[0]} fit vectors, "
            f"shape=({Lpq.shape[0]}, {Lpq.shape[1]}, {Lpq.shape[2]})"
        )

    # ---- RIJCOSX JKBuilder ----------------------------------------------
    with plog.stage("rijcosx_builder"):
        if tight_cell:
            # Periodic-correct GDF J from Lpq + COSX-K.
            # Lpq must be C-contiguous float64 for the pybind11 binding.
            Lpq_contig = np.ascontiguousarray(Lpq, dtype=np.float64)
            jk = make_periodic_tight_cosx_jk_builder(
                basis,
                Lpq_contig,
                system,
                lat_opts,
            )
            plog.info(
                f"RIJCOSX JKBuilder: periodic GDF J ({gdf_method} Lpq, "
                f"{Lpq.shape[0]} fit vectors) "
                "+ periodic COSX K (image-cell exchange summation, "
                f"cutoff {lat_opts.cutoff_bohr:.1f} bohr)"
            )
        else:
            # Molecular-limit path: molecular DF J + home-cell COSX-K.
            jk = make_periodic_gamma_cosx_jk_builder(
                basis,
                aux,
                system,
                exchange_lat_opts,
            )
            plog.info(
                "RIJCOSX JKBuilder: molecular DF J + home-cell COSX K "
                "(vacuum-padded box: no image-cell electrostatics)"
            )

    # ---- SCF loop (delegates to the production C++ engine) --------------
    with plog.stage("scf"):
        rhf_opts = RHFOptions()
        rhf_opts.initial_guess = selection.requested
        rhf_opts.max_iter = opts.max_iter
        rhf_opts.conv_tol_energy = opts.conv_tol_energy
        rhf_opts.conv_tol_grad = float(getattr(opts, "conv_tol_grad", 1e-6))
        rhf_opts.damping = float(opts.damping)
        rhf_opts.use_diis = bool(opts.use_diis)
        rhf_opts.diis_start_iter = int(opts.diis_start_iter)
        rhf_opts.diis_subspace_size = int(opts.diis_subspace_size)
        rhf_opts.level_shift = float(getattr(opts, "level_shift", 0.0))
        rhf_opts.dynamic_damping = bool(getattr(opts, "dynamic_damping", False))

        initial_density = _initial_density_closed(
            system, basis, n_elec // 2, guess, lat_opts, S, options=opts
        )
        result = run_rhf_scf_with_jk(
            basis,
            n_elec,
            S,
            Hcore,
            E_nuc,
            jk,
            rhf_opts,
            initial_density,
            molecule=system.unit_cell_molecule(), guess_selection=selection,
        )

    result = SimpleNamespace(
        overlap=np.asarray(S).copy(), hcore=np.asarray(Hcore).copy(),
        restart_lattice=np.asarray(system.lattice).copy(),
        restart_kpoints=np.zeros((1, 3)), restart_weights=np.ones(1),
        restart_basis=result.restart_basis,
        guess_selection=result.guess_selection,
        energy=result.energy,
        e_electronic=result.e_electronic,
        e_nuclear=E_nuc,
        n_iter=result.n_iter,
        converged=result.converged,
        mo_energies=result.mo_energies,
        mo_coeffs=result.mo_coeffs,
        density=result.density,
        fock=result.fock,
        scf_trace=result.scf_trace,
        omega=0.0,
        grid_shape=(0, 0, 0),
    )

    plog.info(f"SCF {'converged' if result.converged else 'NOT converged'}")
    plog.info(f"  E_total = {result.energy:.10f} Ha")
    plog.info(f"  iters   = {result.n_iter}")

    return result


def run_periodic_rijcosx_rks(
    system: PeriodicSystem,
    basis: BasisSet,
    options=None,
    *,
    functional: str,
    aux_basis: Optional[str] = None,
    grid_options=None,
    tight_cell: Optional[bool] = None,
    progress: Union[bool, ProgressLogger, None] = None,
):
    """Γ-only periodic RKS via RIJCOSX -- vacuum-padded envelope only.

    The closed-shell KS sibling of :func:`run_periodic_rijcosx_rhf`,
    restricted to the molecular-limit (vacuum-padded) regime: the
    dedicated Gamma builder supplies molecular DF J + periodic COSX K
    (exact when image-cell AO overlap is negligible), the XC term is
    integrated on the molecular Becke grid (exact in the same regime --
    the density is compactly supported in the box), and the SCF
    delegates to the production C++ ``run_rks_scf_with_jk``, which
    applies the post-convergence COSX one-center replacement through
    the builder's hook exactly as the RHF driver does.

    **Tight cells fail closed**: their XC needs the periodic-density
    grid (the legacy Gamma RKS route or the true multi-k GDF/COSX
    backend); silently integrating molecular XC there would be wrong.

    Parameters
    ----------
    system, basis, aux_basis, tight_cell, progress
        As in :func:`run_periodic_rijcosx_rhf`.
    options
        ``PeriodicKSOptions`` / ``PeriodicRHFOptions``-like object for
        the SCF controls (max_iter, conv tolerances, DIIS, damping).
        ``None`` uses defaults.
    functional
        libxc functional name (required). Hybrids route their exact-
        exchange fraction through the COSX K builder; pure functionals
        never call K.
    grid_options
        :class:`GridOptions` for the XC quadrature grid (``None`` =
        default XC tier).
    """
    from . import GridOptions, RKSOptions, build_grid, run_rks_scf_with_jk

    opts = options if options is not None else PeriodicRHFOptions()
    selection = _rijcosx_selection(
        system, opts, driver="run_periodic_rijcosx_rks", open_shell=False,
    )
    guess = selection.effective
    lat_opts: LatticeSumOptions = opts.lattice_opts
    plog = resolve_progress(progress)

    n_elec = system.n_electrons()
    if n_elec % 2 != 0:
        raise ValueError(
            "run_periodic_rijcosx_rks: closed-shell RKS requires even "
            f"electron count; got {n_elec}"
        )
    if system.multiplicity != 1:
        raise ValueError(
            "run_periodic_rijcosx_rks: closed-shell RKS requires "
            f"multiplicity=1; got {system.multiplicity}"
        )

    # Envelope gate: the XC term is integrated on the MOLECULAR Becke
    # grid with home-cell AOs, which is exact only when the periodic
    # density is compactly supported inside the cell. `_is_tight_cell`
    # alone is not sufficient here -- it deliberately waves pure-H tight
    # chains through for the J build (molecular DF J is fine there), but
    # their XC is NOT molecular-limit. Require genuine vacuum padding:
    # every active lattice length must exceed the threshold below.
    _RKS_MIN_ACTIVE_LENGTH_BOHR = 12.0
    if tight_cell is None:
        tight_cell = _is_tight_cell(system)
    _active_lengths = [
        float(np.linalg.norm(np.asarray(system.lattice, dtype=float)[:, i]))
        for i in range(int(system.dim))
    ]
    if tight_cell or min(_active_lengths) < _RKS_MIN_ACTIVE_LENGTH_BOHR:
        raise NotImplementedError(
            "run_periodic_rijcosx_rks: Gamma RIJCOSX RKS is implemented "
            "for the vacuum-padded (molecular-limit) envelope only "
            f"(every active lattice length >= "
            f"{_RKS_MIN_ACTIVE_LENGTH_BOHR:.0f} bohr and not a tight "
            "cell) -- tight-cell XC needs the periodic-density grid. "
            "Use the legacy Gamma RKS route (jk_method='gdf') or the "
            "true multi-k GDF/COSX backend (kpoints with >= 2 points)."
        )

    mol = system.unit_cell_molecule()
    aux = _resolve_aux_basis(mol, basis, aux_basis)

    plog.info(
        f"RKS Γ-only RIJCOSX (vacuum-padded envelope) / "
        f"functional={functional}, aux={aux.name}, "
        f"cutoff={lat_opts.cutoff_bohr:.2f} bohr, dim={int(system.dim)}D"
    )

    # Home-cell electrostatics throughout: the molecular DF J has no
    # image electrons (#707; see _home_cell_electrostatics_lat_opts).
    one_e_lat_opts, exchange_lat_opts = _home_cell_electrostatics_lat_opts(
        lat_opts
    )
    with plog.stage("integrals_lattice"):
        S_set = compute_overlap_lattice(basis, system, lat_opts)
        T_set = compute_kinetic_lattice(basis, system, lat_opts)
        V_set = compute_nuclear_lattice_dispatch(basis, system, one_e_lat_opts)
    S = _fold_gamma_real(S_set)
    T = _fold_gamma_real(T_set)
    Hcore = T + _fold_gamma_real(V_set)
    E_nuc = nuclear_repulsion_per_cell(system, one_e_lat_opts)

    with plog.stage("rijcosx_builder"):
        jk = make_periodic_gamma_cosx_jk_builder(
            basis, aux, system, exchange_lat_opts
        )
        plog.info(
            "RIJCOSX JKBuilder: molecular DF J + home-cell COSX K "
            "(vacuum-padded envelope: no image-cell electrostatics)"
        )

    xc_grid = build_grid(mol, grid_options or GridOptions())

    with plog.stage("scf"):
        rks_opts = RKSOptions()
        rks_opts.initial_guess = selection.requested
        rks_opts.functional = str(functional)
        rks_opts.max_iter = int(opts.max_iter)
        rks_opts.conv_tol_energy = float(opts.conv_tol_energy)
        rks_opts.conv_tol_grad = float(getattr(opts, "conv_tol_grad", 1e-6))
        rks_opts.damping = float(opts.damping)
        rks_opts.use_diis = bool(opts.use_diis)
        rks_opts.diis_start_iter = int(opts.diis_start_iter)
        rks_opts.diis_subspace_size = int(opts.diis_subspace_size)

        initial_density = _initial_density_closed(
            system, basis, n_elec // 2, guess, lat_opts, S, options=opts
        )
        res = run_rks_scf_with_jk(
            basis,
            n_elec,
            S,
            Hcore,
            E_nuc,
            jk,
            xc_grid,
            rks_opts,
            initial_density,
            molecule=system.unit_cell_molecule(), guess_selection=selection,
        )

    result = SimpleNamespace(
        overlap=np.asarray(S).copy(), hcore=np.asarray(Hcore).copy(),
        restart_lattice=np.asarray(system.lattice).copy(),
        restart_kpoints=np.zeros((1, 3)), restart_weights=np.ones(1),
        restart_basis=res.restart_basis,
        guess_selection=res.guess_selection,
        energy=res.energy,
        e_electronic=res.e_electronic,
        e_nuclear=E_nuc,
        e_xc=float(getattr(res, "e_xc", 0.0)),
        e_coulomb=float(getattr(res, "e_coulomb", 0.0)),
        e_hf_exchange=float(getattr(res, "e_hf_exchange", 0.0)),
        functional=str(functional),
        n_iter=res.n_iter,
        converged=res.converged,
        mo_energies=res.mo_energies,
        mo_coeffs=res.mo_coeffs,
        density=res.density,
        fock=res.fock,
        scf_trace=res.scf_trace,
        omega=0.0,
        grid_shape=(0, 0, 0),
    )
    plog.info(f"SCF {'converged' if result.converged else 'NOT converged'}")
    plog.info(f"  E_total = {result.energy:.10f} Ha")
    return result


